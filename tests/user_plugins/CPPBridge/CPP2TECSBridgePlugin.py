"""test/CPPBridge/CPP2TECSBridgePlugin.rb の Python 版（C++ ⇒ TECS コンポーネントを生成するシグニチャプラグイン）。"""

from __future__ import annotations

from typing import Any, ClassVar

from tecsgen.context import get_context
from tecsgen.core.cdl_types import VoidType
from tecsgen.core.componentobj.namespace import Namespace
from tecsgen.core.componentobj.namespacepath import NamespacePath
from tecsgen.core.generator import Generator
from tecsgen.core.plugin import CFile
from tecsgen.core.tecsgen import Makefile
from tecsgen.plugin.SignaturePlugin import SignaturePlugin
from tecsgen.ruby_compat import Y, sym, to_s


class CPP2TECSBridgePlugin(SignaturePlugin):
    CPPNamespace = sym("nCPP")

    # クラス変数（このファイルは実行回ごとに読み直すので、実行ごとに空から始まる）
    _instances: ClassVar[
        dict[Any, list[Any]]
    ] = {}  # @signature => [ インスタンスの配列 ]
    _b_written = False  # ファイル .i, .cpp, .hpp 出力済み
    _celltypes: ClassVar[dict[Any, list[Any]]] = {}

    def __init__(self, signature: Any, option: Any) -> None:
        super().__init__(signature, option)

        def check(func_decl: Any, param_decl: Any) -> None:
            if param_decl.get_direction() in (Y.INOUT, Y.OUT, Y.SEND, Y.RECEIVE):
                Generator.error(
                    f"{to_s(param_decl.get_direction()).lower()} parameter cannot be used in Ruby Bridge"
                )

        signature.each_param(check)
        self._celltype_name = f"t{to_s(self._signature.get_name())}"
        self._class_name = f"C{to_s(self._signature.get_name())}"
        cls = CPP2TECSBridgePlugin
        if cls._instances.get(signature):
            cls._instances[signature].append(self)
        else:
            cls._instances[signature] = [self]

        if cls._celltypes.get(self._celltype_name) is None:
            cls._celltypes[self._celltype_name] = [self]
            self.print_msg(
                f"  CPP2TECSBridgePlugin: [signature] {to_s(self._signature.get_namespace_path())} "
                f"=> [celltype] nCPP::{self._celltype_name} => [class] {self._class_name}\n"
            )

            Makefile.add_var("LD", "g++", "default Linker by CPP2TECSBridgePlugin")
            Makefile.add_obj(f"$(_TECS_OBJ_DIR){self._class_name}.o")
            Makefile.add_line(
                "\n"
                "### added by CPP2TECSBridgePlugin (C++ -> TECS Bridge) ###\n"
                "\n"
                "CPPC = g++\n"
                "CPPFLAGS = $(CFLAGS)\n"
                "\n"
                "# vpath for C++\n"
                "vpath %.cpp $(SRC_DIR) $(GEN_DIR)\n"
                "\n"
                "# generic target for C++\n"
                f"$(_TECS_OBJ_DIR){self._class_name}.o : {self._class_name}.cpp\n"
                "\t$(CPPC) -c $(CPPFLAGS) -o $@ $<\n"
                "\n"
                "### end by CPP2TECSBridgePlugin ###\n"
            )
        else:
            cls._celltypes[self._celltype_name].append(self)

    def gen_cdl_file(self, file: Any) -> None:
        """ブリッジセルタイプの生成。"""
        file.print(
            f"namespace {to_s(self.CPPNamespace)} {{\n"
            "  /// C++ => TECS bridge celltype ///\n"
            "  [idx_is_id]\n"
            f"  celltype {self._celltype_name} {{\n"
            f"    call {to_s(self._signature.get_name())} cTECS;\n"
            "  };\n"
            "};\n"
        )

    def gen_postamble(
        self, file: Any, b_singleton: bool, ct_name: Any, global_ct_name: Any
    ) -> None:
        """受け口関数の postamble (C言語)を生成する。"""
        cls = CPP2TECSBridgePlugin
        # mikan namespace
        nsp0 = NamespacePath(self.CPPNamespace, True)
        nsp = nsp0.append(ct_name)
        ct = Namespace.find(nsp)
        self.gen_cpp(ct)
        self.gen_hpp(ct)
        if not cls._b_written:
            cls._b_written = True
            for instances in cls._instances.values():
                nsp = nsp0.append(sym(instances[0].get_celltype_name()))
                ct = Namespace.find(nsp)

    def gen_cpp(self, ct: Any) -> None:
        file = CFile.open(f"{get_context().gen}/{self._class_name}.cpp", "w")
        cn = self._class_name

        file.print(
            "/* This file is generated by CPP2TECSBridgePlugin */\n"
            "\n"
            "#include  <stdlib.h>\n"
            "#include  <memory.h>\n"
            '#include  "t_stddef.h"\n'
            f'#include  "{to_s(self.CPPNamespace)}_{self._celltype_name}_tecsgen.h"\n'
            f'#include  "{cn}.hpp"\n'
            "\n"
        )

        for cell in ct.get_cell_list():
            if cell.is_generate():
                file.print(
                    f'char    CELL_{to_s(cell.get_name())}[] = "{to_s(cell.get_name())}";\n'
                )

        file.print("struct tagName2ID { char *name; ID id; } Name2ID[] = {\n")
        for cell in ct.get_cell_list():
            if cell.is_generate():
                file.print(
                    f"    {{ CELL_{to_s(cell.get_name())}, {to_s(cell.get_id())} }},\n"
                )

        file.print(
            "    { (char*)0, 0 }\n"
            "};\n"
            "\n"
            f"{cn} *\n"
            f"{cn}::join( const char *CellName )\n"
            "{\n"
            "    int   i;\n"
            "    for( i = 0; Name2ID[i].name; i++ )\n"
            "        if( strcmp( CellName, Name2ID[i].name ) == 0 )\n"
            "             break;\n"
            "\n"
            "    if( ! Name2ID[i].name )\n"
            "        return NULL;\n"
            "\n"
            f"\t{cn} *cell = new {cn}( Name2ID[i].id, Name2ID[i].name );\n"
            "\treturn cell;\n"
            "}\n"
            "\n"
            f"{cn}::{cn}( ID id, const char *CellName )\n"
            "{\n"
            "    m_id = id;\n"
            "    m_CellName = CellName;\n"
            "}\n"
            "\n"
        )

        for fh in self._signature.get_function_head_array():  # fh: FuncHead
            fd = fh.get_declarator()  # fd: Decl (ここで fd が関数以外のことはない)
            ft = fd.get_type()  # ft: FuncType
            ret_type = ft.get_type()

            # 関数頭部の出力
            file.print(f"{ft.get_type_str()}\n{cn}::{to_s(fd.get_name())}(")
            delim = ""
            for p in ft.get_paramlist().get_items():  # p: ParamDecl
                # size_is, count_is, string, send, receive には対応しない
                pd = p.get_declarator()  # pd: Decl
                file.print(
                    f"{delim} {pd.get_type().get_type_str()} {to_s(pd.get_name())}"
                    f"{pd.get_type().get_type_str_post()}"
                )
                delim = ", "
            file.print(" )\n{\n")

            # 戻り値を記憶する変数の定義を出力
            if isinstance(ret_type.get_original_type(), VoidType):
                retval = ""
                retnul = ""
            elif ret_type.get_type_str() in ("ER", "ER_UINT"):
                file.print(
                    f"    {ft.get_type().get_type_str()}    retval{ft.get_type().get_type_str_post()};\n"
                )
                retval = "retval = "
                retnul = "E_ID"
            else:
                file.print(
                    f"    {ft.get_type().get_type_str()}    retval{ft.get_type().get_type_str_post()};\n"
                )
                retval = "retval = "
                retnul = "0"

            file.print(
                "    if( ! VALID_IDX( m_id ) )\n"
                f"         return {retnul};\n"
                "    CELLCB *p_cellcb = (CELLCB*)GET_CELLCB( m_id );\n"
            )

            file.print(f"    {retval}cTECS_{to_s(fd.get_name())}( ")
            delim = ""
            for p in ft.get_paramlist().get_items():
                pd = p.get_declarator()
                file.print(f"{delim}{to_s(pd.get_name())}")
                delim = ", "
            file.print(" );\n")
            if not isinstance(ret_type.get_original_type(), VoidType):
                file.print("    return    retval;\n")
            file.print("}\n\n")

        file.close()

    def gen_hpp(self, ct: Any) -> None:
        file = CFile.open(f"{get_context().gen}/{self._class_name}.hpp", "w")
        file.print("/* This file is generated by CPP2TECSBridgePlugin */\n\n")
        self.gen_class(file)
        file.close()

    def gen_class(self, file: Any) -> None:
        cn = self._class_name
        file.print(
            f"class {cn} {{\n"
            "public:\n"
            "    /*\n"
            "     * join:  join to TECS cell.\n"
            "     *\n"
            "     * If CellName not found, NULL is returned.\n"
            "     *\n"
            f"     * In 'join',  new {cn}( ) is called.\n"
            "     * So you have to delete after using the joined instance.\n"
            "     */\n"
            f"    static {cn} *join( const char *CellName );\n"
        )

        for fh in self._signature.get_function_head_array():  # fh: FuncHead
            fd = fh.get_declarator()
            ft = fd.get_type()

            # 関数頭部の出力
            file.print(f"    {ft.get_type_str()} {to_s(fd.get_name())}(")
            delim = ""
            for p in ft.get_paramlist().get_items():
                pd = p.get_declarator()
                file.print(
                    f"{delim} {pd.get_type().get_type_str()} {to_s(pd.get_name())}"
                    f"{pd.get_type().get_type_str_post()}"
                )
                delim = ", "
            file.print(" );\n")

        file.print(
            "\n"
            "private:\n"
            f"    {cn}( ID id, const char *CellName );\n"
            f"    {cn}();\n"
            "\n"
            "    ID          m_id;\n"
            "    const char  *m_CellName;\n"
            "};\n"
            "\n"
        )

    def get_celltype_name(self) -> Any:
        return self._celltype_name
