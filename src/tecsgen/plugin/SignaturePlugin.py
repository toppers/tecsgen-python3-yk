"""SignaturePlugin.rb の移植（内部仕様9.1節）。

signature プラグインの共通の親クラス。SignaturePlugin は、シグニチャプラグインの共通の
親クラスであるが、何もしないで受け口から呼び口を呼び出す（スルーする）プラグインとしても
使用できる。
"""

from __future__ import annotations

import re
from typing import Any, ClassVar

from tecsgen.core.plugin import Plugin
from tecsgen.core.syntaxobj.cdlstring import CDLString
from tecsgen.ruby_compat import Y, class_name, sub_first, sym, to_s

_IDENT_RE = re.compile(r"\A[A-Za-z_][0-9A-Za-z_]*\Z")


class SignaturePlugin(Plugin):
    """@signature:: Signature   プラグインの対象となるシグニチャ / @option:: str"""

    SIGNATURE_PLUGIN_ARG_PROC: ClassVar[dict[str, Any]] = {}

    def __init__(self, signature: Any, option: Any) -> None:
        """signature:: Signature   シグニチャ（インスタンス）"""
        super().__init__()
        self._signature = signature
        self._plugin_arg_str = CDLString.remove_dquote(option)
        self._plugin_arg_list = {}
        self._celltype_name = sym(
            f"t{class_name(type(self))}_{to_s(signature.get_global_name())}"
        )

        # シグニチャ名の接頭文字 s を取り除く(なければ取り除かない)
        port_name = sub_first(r"\As(.*)", r"\1", to_s(signature.get_name()))
        self._entry_port_name = sym(f"e{port_name}")
        self._call_port_name = sym(f"c{port_name}")

        # 子クラスの場合は、SignaturePlugin の引数は受け付けない
        if class_name(type(self)) == "SignaturePlugin":
            self._plugin_arg_check_proc_tab = SignaturePlugin.SIGNATURE_PLUGIN_ARG_PROC
            self.parse_plugin_arg()

    @classmethod
    def gen_post_code(cls, file: Any) -> None:
        """後ろのコードを生成する。複数のプラグインの post_code が一つのファイルに含まれるため、見出しをつけること。"""

    ### 構文解釈段階で呼び出されるメソッド ###
    # generate 指定子の場合、構文解釈次第(end_of_parseで)呼び出される
    # generate 文の場合、出現次第呼び出される

    def gen_cdl_file(self, file: Any) -> None:
        """CDL ファイルの生成。"""
        send_receive: list[tuple[Any, Any, Any]] = []
        if self._signature is not None:

            def collect(fd: Any, param: Any) -> None:
                d = param.get_direction()
                if d in (Y.SEND, Y.RECEIVE):
                    send_receive.append((d, fd, param))

            self._signature.each_param(collect)

        file.print(
            "/*\n"
            " * generated by SignaturePlugin \n"
            f" *   signature: {to_s(self._signature.get_namespace_path())}\n"
            f" *   celltype:  {to_s(self._celltype_name)} (identity celltype)\n"
            " */\n"
            f"celltype {to_s(self._celltype_name)} {{\n"
        )

        if len(send_receive) > 0:
            file.print("  [allocator(             /* relay allocator */\n")
            delim = ""
            for _d, fd, param in send_receive:
                file.print(
                    f"{delim}\t{to_s(fd.get_name())}.{to_s(param.get_name())}<="
                    f"{to_s(self._call_port_name)}.{to_s(fd.get_name())}.{to_s(param.get_name())}"
                )
                delim = ",\n"
            file.print("), inline]\n")
        else:
            file.print("  [inline]\n")

        file.print(
            f"  entry {to_s(self._signature.get_namespace_path())} {to_s(self._entry_port_name)};\n"
            f"  call  {to_s(self._signature.get_namespace_path())} {to_s(self._call_port_name)};\n"
            "};\n"
        )

    ### コード生段階で呼び出されるメソッド ###

    def gen_ep_func_body(
        self,
        file: Any,
        b_singleton: bool,
        ct_name: Any,
        global_ct_name: Any,
        sig_name: Any,
        ep_name: Any,
        func_name: Any,
        func_global_name: Any,
        func_type: Any,
        params: list[Any],
    ) -> None:
        """受け口関数の本体(C言語)を生成する。

        通常であれば、ジェネレータは受け口関数のテンプレートを生成する。プラグインの場合、
        変更する必要のないセルタイプコードを生成する。
        """
        ret_type = func_type.get_type()
        b_ret_void = ret_type.is_void()

        if not b_ret_void:
            file.print(f"  {ret_type.get_type_str()}  retval;\n")

        if not b_singleton:
            file.print(
                f"  CELLCB *p_cellcb = {to_s(global_ct_name)}_GET_CELLCB(idx);\n\n"
            )

        if not b_ret_void:
            file.print("  retval = ")
        else:
            file.print("  ")

        file.print(f"{to_s(self._call_port_name)}_{to_s(func_name)}(")

        delim = ""
        for param in params:
            file.printf(f"{delim} {to_s(param.get_name())}")
            delim = ","

        file.print(" );\n")

        if not b_ret_void:
            file.print("  return retval;\n")

    ### プラグイン引数のチェック ###

    def set_celltypeName(self, rhs: str) -> None:
        """プラグイン引数 celltypeName のチェック。"""
        self._celltype_name = sym(rhs)
        if not _IDENT_RE.match(self._celltype_name):
            self.cdl_error(
                "SignaturePlugin: '$1' celltype_name using unsuitable character",
                self._celltype_name,
            )

    def set_callName(self, rhs: str) -> None:
        """プラグイン引数 callName のチェック。"""
        self._call_port_name = sym(rhs)
        if not _IDENT_RE.match(self._call_port_name):
            self.cdl_error(
                "SignaturePlugin: '$1' callName using unsuitable character",
                self._call_port_name,
            )

    def set_entryName(self, rhs: str) -> None:
        """プラグイン引数 entryName のチェック。"""
        self._entry_port_name = sym(rhs)
        if not _IDENT_RE.match(self._entry_port_name):
            self.cdl_error(
                "SignaturePlugin: '$1' entryName using unsuitable character",
                self._entry_port_name,
            )


SignaturePlugin.SIGNATURE_PLUGIN_ARG_PROC = {
    "celltypeName": lambda obj, rhs: obj.set_celltypeName(rhs),
    "callName": lambda obj, rhs: obj.set_callName(rhs),
    "entryName": lambda obj, rhs: obj.set_entryName(rhs),
}
