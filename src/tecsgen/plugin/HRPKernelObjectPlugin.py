"""HRPKernelObjectPlugin.rb の移植（内部仕様9章）。HRP カーネルオブジェクト用セルタイププラグインの共通の親クラス。"""

from __future__ import annotations

from typing import Any, ClassVar

from tecsgen.context import dbg_print, get_context
from tecsgen.core.cdl_types import ArrayType
from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import Y, to_s


class HRPKernelObjectPlugin(CelltypePlugin):
    # カーネルオブジェクトセルタイプの管理
    # HRPKernelObjectPluginクラスに対してメソッド呼出しを行うことを想定
    _checked: ClassVar[bool] = False
    _celltype_list: ClassVar[list[Any]] = []
    _region_list: ClassVar[list[Any]] = []

    @classmethod
    def reset(cls) -> None:
        HRPKernelObjectPlugin._checked = False
        HRPKernelObjectPlugin._celltype_list = []
        HRPKernelObjectPlugin._region_list = []

    def __init__(self, celltype: Any, option: Any) -> None:
        super().__init__(celltype, option)
        # それぞれのカーネルオブジェクトを解析対象セルタイプに追加
        # 目的：
        #  - カーネルオブジェクトのセルをメモリ保護対象外とする
        #   - カーネルオブジェクト本体の管理はTECSでなくOSで実施するため
        #  - カーネルオブジェクトのセルへのアクセスを直接関数呼出しとする
        #   - システムサービス呼出しはOSが提供するため
        HRPKernelObjectPlugin.set_celltype(celltype)

    def print_cfg_cre(self, file: Any, cell: Any, val: Any, tab: Any) -> None:
        """各種カーネルオブジェクトのCRE_*の出力。"""
        raise RuntimeError(
            f"called virtual method print_cfg_cre in {to_s(self._celltype.get_name())} plugin"
        )

    def print_cfg_sac(self, file: Any, val: Any, acv: Any) -> None:
        """各種カーネルオブジェクトのSAC_*の出力。"""
        raise RuntimeError(
            f"called virtual method print_cfg_sac in {to_s(self._celltype.get_name())} plugin"
        )

    def gen_factory(self, file: Any) -> None:
        """セルタイププラグインの本体メソッド。静的APIの生成。"""
        from tecsgen.core.generate import AppFile
        from tecsgen.plugin.HRPPlugin import HRPPlugin

        gen = get_context().gen
        ct = self._celltype
        dbg_print(f"===== begin {to_s(ct.get_name())} plugin =====\n")

        # 対象となるすべてのセルについて、受け口に結合されているセルの所属ドメインを解析
        #  - 生成すべきcfgファイル名を取得するために必要
        if not HRPKernelObjectPlugin.is_checked():
            HRPKernelObjectPlugin.check_referenced_cells()
        else:
            dbg_print("***** already checked\n")

        # 追記するために AppFile を使う（文字コード変換されない）
        file2 = AppFile.open(f"{gen}/tecsgen.cfg")
        file2.print(f"\n/* Generated by {type(self).__name__} */\n\n")

        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            dbg_print(f"===== begin check my domain {to_s(cell.get_name())} =====\n")
            # カーネルオブジェクトの属性を，valにコピー
            val: dict[Any, Any] = {}
            for a in ct.get_attribute_list():
                if isinstance(a.get_type(), ArrayType):
                    val[a.get_name()] = []
                    j = cell.get_join_list().get_item(a.get_name())
                    if j is not None:
                        # セル生成時に初期化する場合
                        for elem in j.get_rhs():
                            val[a.get_name()].append(to_s(elem))
                    elif a.get_initializer() is not None:
                        # セルタイプの初期化値を使う場合
                        for elem in a.get_initializer():
                            val[a.get_name()].append(to_s(elem))
                    else:
                        raise RuntimeError("attribute is not initialized")
                else:
                    j = cell.get_join_list().get_item(a.get_name())
                    if j is not None:
                        # セル生成時に初期化する場合
                        val[a.get_name()] = to_s(j.get_rhs())
                    elif a.get_initializer() is not None:
                        # セルタイプの初期化値を使う場合
                        val[a.get_name()] = to_s(a.get_initializer())
                    else:
                        raise RuntimeError("attribute is not initialized")
            # generate.rbを参考に $id$を置換
            if val.get(Y.id) is not None:
                name_array = ct.get_name_array(cell)
                val[Y.id] = ct.subst_name(val[Y.id], name_array)
            # $cbp$の代わり
            cell_domain_root = cell.get_region().get_domain_root()
            cell_domain_type = cell_domain_root.get_domain_type()

            # CRE_XXX/DEF_XXXの生成
            if to_s(cell_domain_type.get_option()) != "OutOfDomain":
                # 保護ドメインに属する場合
                if not HRPKernelObjectPlugin.include_region(
                    to_s(cell_domain_root.get_name())
                ):
                    # その保護ドメインの.cfgが生成されていない場合
                    HRPKernelObjectPlugin.set_region_list(
                        to_s(cell_domain_root.get_name())
                    )
                    dbg_print(
                        f"~~~~~ {to_s(cell_domain_root.get_name())} is registered!\n"
                    )
                else:
                    dbg_print(
                        f"~~~~~ {to_s(cell.get_region().get_namespace_path())} is included in"
                    )
                file3 = AppFile.open(
                    f"{gen}/tecsgen_{to_s(cell_domain_root.get_global_name())}.cfg"
                )
                self.print_cfg_cre(file3, cell, val, "")
                file3.close()
            else:
                # 無所属の場合
                dbg_print(
                    f"~~~~~ {to_s(cell_domain_root.get_namespace_path())} is OutOfDomain\n"
                )
                name = cell_domain_root.get_name()
                if type(name) is str and name == "::":
                    self.print_cfg_cre(file2, cell, val, "")
                else:
                    file3 = AppFile.open(f"{gen}/tecsgen_{to_s(name)}.cfg")
                    self.print_cfg_cre(file3, cell, val, "")
                    file3.close()

            dbg_print(f"===== end check my domain {to_s(cell.get_name())} =====\n")

            # SAC_XXXの生成
            if val.get(Y.accessPattern1) is not None:
                dbg_print(f"===== begin check regions {to_s(cell.get_name())} =====\n")
                acv: dict[Any, Any] = {
                    Y.accessPattern1: val.get(Y.accessPattern1),
                    Y.accessPattern2: val.get(Y.accessPattern2),
                    Y.accessPattern3: val.get(Y.accessPattern3),
                    Y.accessPattern4: val.get(Y.accessPattern4),
                }
                acv_tmp: list[str] = []
                domain_roots = HRPPlugin.get_inter_domain_join_roots(cell)
                # 結合先セルのドメインを加える
                if cell_domain_type.get_kind() != Y.OutOfDomain:
                    domain_roots.append(cell_domain_root)
                for dr in domain_roots:
                    kind = dr.get_domain_type().get_kind()
                    if kind == Y.user:
                        acv_tmp.append(f"TACP({to_s(dr.get_name())})")
                    elif kind == Y.kernel:
                        acv_tmp.append("TACP_KERNEL")
                    elif (
                        kind == Y.OutOfDomain
                        and cell_domain_type.get_kind() == Y.OutOfDomain
                    ):
                        # 呼び元も、呼び先も OutOfDomain の場合
                        acv_tmp.append("TACP_SHARED")
                # uniq!
                uniq: list[str] = []
                for s in acv_tmp:
                    if s not in uniq:
                        uniq.append(s)
                acv_tmp = uniq
                if len(acv_tmp) == 0:
                    # 呼び先セルが無所属かつ、呼び元も無所属のみ、または結合無しの場合
                    acv_tmp = ["TACP_SHARED"]
                b_info = False
                b_warn = False
                for key in list(acv.keys()):
                    acp = acv[key]
                    if acp is None:
                        continue
                    if acp != "OMIT":
                        pass
                    elif cell_domain_type.get_kind() != Y.OutOfDomain:
                        roots = HRPPlugin.get_inter_domain_join_roots(cell)
                        for dr in roots:
                            kind = dr.get_domain_type().get_kind()
                            if kind == Y.kernel:
                                pass
                            elif kind == Y.user:
                                # 他のユーザードメインからの結合
                                b_other_user = to_s(dr.get_namespace_path()) != to_s(
                                    cell.get_region()
                                    .get_domain_root()
                                    .get_namespace_path()
                                )
                                if b_other_user and not b_warn:
                                    self.cdl_error(
                                        "HRP9999 '$1': kernel object joined from other user domain. "
                                        "kernel object joined from multi-user-domain must be placed out of domain",
                                        cell.get_name(),
                                    )
                                    b_warn = True
                            elif kind == Y.OutOfDomain:
                                # 無所属からの結合
                                if (
                                    not b_info
                                    and cell_domain_type.get_kind() == Y.OutOfDomain
                                ):
                                    # この情報は、不要と判断する
                                    b_info = True
                            else:
                                raise RuntimeError("unknown domain kind")
                    if acp == "OMIT":
                        acv[key] = "|".join(acv_tmp)
                # 各種SACの生成
                domain_option = cell_domain_type.get_option()
                if (
                    to_s(domain_option) != "OutOfDomain"
                    or cell.get_region().get_domain_root().get_name() != "::"
                ):
                    # 保護ドメインに属する場合
                    file3 = AppFile.open(
                        f"{gen}/tecsgen_{to_s(cell.get_region().get_name())}.cfg"
                    )
                    self.print_cfg_sac(file3, val, acv)
                    file3.close()
                else:
                    # 無所属の場合
                    self.print_cfg_sac(file2, val, acv)

                dbg_print(f"===== end check regions {to_s(cell.get_name())} =====\n")
        dbg_print(f"===== end {to_s(ct.get_name())} plugin =====\n")
        file2.close()

    @classmethod
    def is_checked(cls) -> bool:  # Ruby: isChecked
        return HRPKernelObjectPlugin._checked

    @classmethod
    def check_referenced_cells(cls) -> None:
        dbg_print("===== begin check registered celltype =====\n")
        for ct in cls.get_celltype_list():
            dbg_print(to_s(ct.get_name()) + "\n")
        dbg_print("===== end check registered celltype =====\n")
        HRPKernelObjectPlugin._checked = True

    @classmethod
    def set_celltype(cls, celltype: Any) -> None:
        HRPKernelObjectPlugin._celltype_list.append(celltype)

    @classmethod
    def get_celltype_list(cls) -> list[Any]:
        return HRPKernelObjectPlugin._celltype_list

    @classmethod
    def set_region_list(cls, region: Any) -> None:
        HRPKernelObjectPlugin._region_list.append(region)

    @classmethod
    def include_region(cls, region: Any) -> bool:
        return region in HRPKernelObjectPlugin._region_list

    @classmethod
    def include_celltype(cls, celltype: Any) -> bool:  # Ruby: include_celltype?
        return any(celltype is c for c in HRPKernelObjectPlugin._celltype_list)
