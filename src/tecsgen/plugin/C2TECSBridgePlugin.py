"""C2TECSBridgePlugin.rb の移植（内部仕様9章）。

C の関数からシグニチャの関数（呼び口）を呼び出せるようにするブリッジセルタイプと、
その関数のプロトタイプ宣言のヘッダを生成するシグニチャプラグイン。

@signature:: Signature   プラグインの対象となるシグニチャ
@option:: str   '"', '"' で囲まれた文字列
"""

from __future__ import annotations

import re
from typing import Any, ClassVar

from tecsgen.plugin.SignaturePlugin import SignaturePlugin
from tecsgen.ruby_compat import RubyIO, sym, to_s


class C2TECSBridgePlugin(SignaturePlugin):
    # プラグイン引数名と Proc
    C2TECS_BRIDGE_PLUGIN_ARG_PROC: ClassVar[dict[str, Any]] = {
        "prefix": lambda obj, rhs: obj.set_prefix(rhs),
        "suffix": lambda obj, rhs: obj.set_suffix(rhs),
        "header_name": lambda obj, rhs: obj.set_header_name(rhs),
    }

    # シグニチャのグローバル名 → プラグインインスタンスのリスト（@@signature_list）
    _signature_list: ClassVar[dict[Any, list[Any]]] = {}

    @classmethod
    def reset(cls) -> None:
        """`@@signature_list` を初期化する（1プロセスで何度も実行するテスト用）。"""
        C2TECSBridgePlugin._signature_list = {}

    def __init__(self, signature: Any, option: Any) -> None:
        """signature:: Signature        シグニチャ（インスタンス）"""
        from tecsgen.context import get_context

        super().__init__(signature, option)

        self._signature = signature
        self._header_name = (
            f"{get_context().gen}/C2TECS_{to_s(self._signature.get_global_name())}.h"
        )
        self._prefix = ""
        self._suffix = ""
        self._celltype_name = sym(f"t{to_s(self._signature.get_global_name())}")
        self._plugin_arg_check_proc_tab = (
            C2TECSBridgePlugin.C2TECS_BRIDGE_PLUGIN_ARG_PROC
        )
        self.parse_plugin_arg()

    def gen_cdl_file(self, file: Any) -> None:
        lst = C2TECSBridgePlugin._signature_list
        gname = self._signature.get_global_name()
        if lst.get(gname) is not None:
            lst[gname].append(self)
            self.cdl_warning(
                "C2TW001 signature '$1' duplicate. ignored current one",
                self._signature.get_namespace_path(),
            )
            return

        lst[gname] = [self]
        self.print_msg(
            f"  C2TECSBridgePlugin: [celltype] C2TECS::{to_s(self._celltype_name)}. "
            "Create cell then join the call port 'cCall' to the target cell\n"
        )
        file.print(
            "namespace nC2TECS{\n"
            "  [singleton, active]    // this celltype is not active actually. 'active' is specified to prevent W1002.\n"
            f"  celltype {to_s(self._celltype_name)} {{\n"
            f"    call {to_s(self._signature.get_namespace_path())} cCall;\n"
            "  };\n"
            "};\n"
        )

    @classmethod
    def gen_post_code(cls, file: Any) -> None:
        """後ろのコードを生成する（何も出力しない）。"""

    def gen_ep_func_body(
        self,
        file: Any,
        b_singleton: bool,
        ct_name: Any,
        global_ct_name: Any,
        sig_name: Any,
        ep_name: Any,
        func_name: Any,
        func_global_name: Any,
        func_type: Any,
        params: list[Any],
    ) -> None:
        """受け口関数の本体(C言語)を生成する（nothing to do）。"""

    def gen_postamble(
        self, file: Any, b_singleton: bool, ct_name: Any, global_ct_name: Any
    ) -> None:
        # Ruby 版は CFile ではなく Kernel#open で書く（文字コードの変換をしない）
        header_file = RubyIO(self._header_name, "w", "utf-8")

        sig_path = to_s(self._signature.get_namespace_path())
        sig_gname = to_s(self._signature.get_global_name())
        header_comment = (
            "/*\n"
            " * This file was generated by C2TECSBridgePlugin and has prototype\n"
            f" * decalarations of functions in signature '{sig_path}'\n"
            " */\n"
            "\n"
        )

        file.print(header_comment)
        header_file.print(header_comment)
        header_file.print(
            f"#ifndef {sig_gname}__h\n"
            f"#define {sig_gname}__h\n"
            "\n"
            "/*\n"
            " * function prototype declarations\n"
            f" *    signature: '{sig_path}'\n"
            " *\n"
            " * These functions can be called from C sources directly.\n"
            " * If function name collides, please consider to specify 'prefix' option for C2TECSBridgePlugin.\n"
            " */\n"
        )

        # generate C functions calling function of call port
        for func_head in self._signature.get_function_head_array():
            func_name = to_s(func_head.get_name())
            ret_type = func_head.get_return_type()
            params = func_head.get_paramlist().get_items()

            # function header
            file.print(f"{ret_type.get_type_str()}\n")
            header_file.printf("%-16s", ret_type.get_type_str())
            file.print(f"{self._prefix}{func_name}{self._suffix}(")
            header_file.print(f"{self._prefix}{func_name}{self._suffix}(")

            delim = ""
            for param in params:
                # Ruby 版は書式文字列として printf に渡している（引数なし）
                s = (
                    f"{delim} {param.get_type().get_type_str()} {to_s(param.get_name())}"
                    f"{param.get_type().get_type_str_post()}"
                )
                file.printf(s)
                header_file.printf(s)
                delim = ","
            file.print(" )\n{\n")
            header_file.print(" );\n")

            # call function in call port
            if not ret_type.is_void():
                file.print(f"  {ret_type.get_type_str()}  retval;\n")
                file.print("  retval = ")
            else:
                file.print("  ")

            file.print(f"cCall_{func_name}(")

            delim = ""
            for param in params:
                file.printf(f"{delim} {to_s(param.get_name())}")
                delim = ","
            file.print(" );\n")

            if not ret_type.is_void():
                file.print("  return retval;\n")
            file.print("}\n\n")

        header_file.print(f"\n#endif /* {sig_gname}__h */\n\n")
        header_file.close()

    def set_prefix(self, rhs: Any) -> None:
        """prefix プラグインオプション。"""
        self._prefix = to_s(rhs)

    def set_suffix(self, rhs: Any) -> None:
        """suffix プラグインオプション。"""
        self._suffix = to_s(rhs)

    def set_header_name(self, rhs: Any) -> None:
        """header_name プラグインオプション。"""
        from tecsgen.context import get_context

        self._header_name = f"{get_context().gen}/" + to_s(rhs)
        # Ruby の \Z は末尾の改行の直前にも一致する
        if not re.search(r"\.h(?=\n?\Z)", self._header_name):
            self._header_name += ".h"
