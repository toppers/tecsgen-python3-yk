"""RPCPlugin.rb の移植（内部仕様9章）。Transparent RPC チャンネルを生成するプラグイン。

mikan through plugin: namespace が考慮されていない

以下を仮定（制限事項）:
  呼び元、呼び先のエンディアン、char, short, int_t, long_t, intptr_t のサイズが同じ
  有符号、無符号でサイズが同じ

**既知の問題だった点（内部仕様9.7.1）**: このプラグインが `gen_marshaler_celltype_` で生成する CDL の
`generate(TransparentRPCSignaturePlugin, ...)` が参照するクラスは、r3304 には存在しなかった。
実行すると Ruby 版・この移植のどちらも `P2001 TransparentRPCSignaturePlugin.rb : fail to load plugin`
で失敗していた。tecsgen-rb で `TransparentRPCSignaturePlugin.rb` が追加されたため、この移植でも
`plugin/TransparentRPCSignaturePlugin.py` を移植し、`rpc`・`class`・`DataPumpHolder` が成功するようになった。
"""

from __future__ import annotations

from typing import Any, ClassVar

from tecsgen.plugin.lib.GenParamCopy import GenParamCopy
from tecsgen.plugin.lib.GenTransparentMarshaler import GenTransparentMarshaler
from tecsgen.plugin.ThroughPlugin import ThroughPlugin
from tecsgen.ruby_compat import Symbol, sym, to_s, truthy, utf8_literal


class RPCPlugin(GenParamCopy, GenTransparentMarshaler, ThroughPlugin):
    # RPCPlugin 専用のオプション（GenTransparentMarshaler.RPC_PLUGIN_ARG_PROC の複製 + 追加）
    TRANSPARENT_RPC_PLUGIN_ARG_PROC: ClassVar[dict[str, Any]] = {}

    def __init__(
        self,
        cell_name: Any,
        plugin_arg: Any,
        next_cell: Any,
        next_cell_port_name: Any,
        next_cell_port_subscript: Any,
        signature: Any,
        celltype: Any,
        caller_cell: Any,
    ) -> None:
        """説明は ThroughPlugin (plugin.rb) を参照。"""
        super().__init__(
            cell_name,
            plugin_arg,
            next_cell,
            next_cell_port_name,
            next_cell_port_subscript,
            signature,
            celltype,
            caller_cell,
        )
        self._b_no_client_semaphore = False
        self._semaphore_celltype = "tSemaphore"
        self.initialize_transparent_marshaler(cell_name)

        # オプション：GenTransparentMarshaler 参照
        self._plugin_arg_check_proc_tab = RPCPlugin.TRANSPARENT_RPC_PLUGIN_ARG_PROC
        self.parse_plugin_arg()

        self._rpc_channel_celltype_name = f"tRPCPlugin_{to_s(self._tdr_celltype)}_{to_s(self._signature.get_global_name())}"
        self._rpc_channel_celltype_name_full = (
            f"tRPCPlugin_{to_s(self._tdr_celltype)}_{to_s(self._channel_celltype)}_"
            f"{to_s(self._signature.get_global_name())}"
        )
        from tecsgen.context import get_context

        self._rpc_channel_celltype_file_name = (
            f"{get_context().gen}/{self._rpc_channel_celltype_name}.cdl"
        )

        if self._signature.need_PPAllocator() and self._pp_allocator_size is None:
            self.cdl_error(
                "RPC9999 PPAllocatorSize must be speicified for oneway [in] array"
            )

    def gen_plugin_decl_code(self, file: Any) -> None:
        """plugin の宣言コード (celltype の定義) 生成。"""
        ct_name = f"{to_s(self._ct_name)}_{to_s(self._channel_celltype)}"

        # このセルタイプ（同じシグニチャ）は既に生成されているか？
        # Ruby 版は ct_name が str（@ct_name は Symbol）なので、ThroughPlugin/TracePlugin の
        # Symbol キーとは別枠のエントリになる（意図的に同じ Hash を共有している）
        if RPCPlugin._generated_celltype.get(ct_name) is None:
            RPCPlugin._generated_celltype[ct_name] = [self]
        else:
            RPCPlugin._generated_celltype[ct_name].append(self)
            return

        self.gen_marshaler_celltype_(file)

    def gen_through_cell_code(self, file: Any) -> None:
        """through cell コードを生成。"""
        from tecsgen.core.componentobj.namespace import Namespace

        self.gen_plugin_decl_code(file)

        # セルを探す
        cell = Namespace.find(self._next_cell.get_namespace_path())

        subsc = (
            f"[{to_s(self._next_cell_port_subscript)}]"
            if truthy(self._next_cell_port_subscript)
            else ""
        )
        file.print(
            "/*\n"
            " * generated by RPCPlugin\n"
            f" *   start_region={to_s(self._start_region.get_namespace_path())}\n"
            f" *   end_region  ={to_s(self._end_region.get_namespace_path())}\n"
            f" *   next_cell.entry={self._next_cell.get_namespace_path().get_path_str()}."
            f"{to_s(self._next_cell_port_name)}{subsc}\n"
            "/ */\n"
            f'import( "{self._rpc_channel_celltype_file_name}" );\n\n'
        )

        nest = self._region.gen_region_str_pre(file)
        indent_str = "  " * nest
        subscript = (
            f"[{to_s(self._next_cell_port_subscript)}]"
            if truthy(self._next_cell_port_subscript)
            else ""
        )

        file.print(
            f"{indent_str}"
            + utf8_literal("// 一方向チャンネルセル\n")
            + f"{indent_str}cell {to_s(self._channel_celltype)} {to_s(self._channel_cell_name)} {{\n"
            f"{indent_str}}};\n\n"
            f"{indent_str}" + utf8_literal("// RPC チャンネルセル\n")
        )

        # #473 が解決された場合、composite リレーアロケータに変更すべき
        # アロケータの指定があるか？
        if len(cell.get_allocator_list()) > 0:
            file.print(f"{indent_str}[allocator(")

            delim = ""
            for type_, eport, subsc2, func, buf, alloc in cell.get_allocator_list():
                file.print(delim)
                delim = f",\n{indent_str}           "  # 最終行には出さない

                subsc_str = "[#{subsc}]" if subsc2 else ""

                eport = "eThroughEntry"  # RPCの受け口名に変更
                file.print(
                    f"{eport}{subsc_str}.{to_s(func)}.{to_s(buf)} = {to_s(alloc)}"
                )

            file.puts(")]")

        file.print(
            f"{indent_str}cell {self._rpc_channel_celltype_name} {to_s(self._cell_name)} {{\n"
            f"{indent_str}  {to_s(self._call_port_name)} = "
            f"{self._next_cell.get_namespace_path().get_path_str()}."
            f"{to_s(self._next_cell_port_name)}{subscript};\n"
            f"{indent_str}  cTDR         = {to_s(self._channel_cell_name)}.eTDR;\n"
            f"{indent_str}  cEventflag   = {to_s(self._channel_cell_name)}.eEventflag;\n"
            f"{indent_str}  taskPriority = {to_s(self._task_priority)};\n"
            f"{indent_str}}};\n"
        )
        self._region.gen_region_str_post(file)

    def gen_marshaler_celltype_(self, file: Any) -> None:
        file.print(
            "/* generated by RPCPlugin / */\n"
            f"generate( TransparentRPCSignaturePlugin, "
            f'{to_s(self._signature.get_namespace_path())}, "{to_s(self._plugin_arg_str)}");\n'
            f'import( "{self._marshaler_celltype_file_name}" );\n'
        )

    def set_noClientSemaphore(self, rhs: Any) -> None:
        """プラグイン引数 noClientSemaphore のチェック。"""
        rhs_sym = sym(rhs)
        if rhs_sym == Symbol("true"):
            self._b_no_client_semaphore = True
        elif rhs_sym == Symbol("false"):
            self._b_no_client_semaphore = False
        else:
            self.cdl_error("RPC9999 specify true or false for noClientSemaphore")

    def set_semaphoreCelltype(self, rhs: Any) -> None:
        """プラグイン引数 semaphoreCelltype のチェック。"""
        from tecsgen.core.componentobj.celltype import Celltype
        from tecsgen.core.componentobj.compositecelltype import CompositeCelltype
        from tecsgen.core.componentobj.namespace import Namespace
        from tecsgen.core.componentobj.namespacepath import NamespacePath

        self._semaphore_celltype = sym(rhs)
        nsp = NamespacePath.analyze(to_s(self._semaphore_celltype))
        obj = Namespace.find(nsp)
        if not isinstance(obj, (Celltype, CompositeCelltype)):
            self.cdl_error(
                "RPC9999 semaphoreCelltype '$1' not celltype or not defined", rhs
            )


RPCPlugin.TRANSPARENT_RPC_PLUGIN_ARG_PROC = {
    **GenTransparentMarshaler.RPC_PLUGIN_ARG_PROC,
    "noClientSemaphore": lambda obj, rhs: obj.set_noClientSemaphore(rhs),
    "semaphoreCelltype": lambda obj, rhs: obj.set_semaphoreCelltype(rhs),
}
