"""DataPumpHolderPlugin.rb の移植（内部仕様9章）。データポンプ＆ホルダ生成プラグイン（セルタイププラグイン）。

このプラグインが適用されたセルタイプの属性（読出し専用データ）・変数（読書き可能データ）を
授受するためのセルタイプ（データポンプ・データホルダ）と、シグニチャ（Get・Set）を生成する。

`DataPumpHolder` オラクルケースでは、生成した CDL が参照する `TransparentRPCSignaturePlugin` が
存在しないため Ruby 版自身もコード生成の前に失敗する（[[tecsgen内部仕様 - 09 プラグイン機構#9.7.1]]
の既知の問題）。そのため、実行される CDL の生成までを移植し、コード生成段階でだけ呼ばれる
`gen_ep_func_body`（Ruby 約230行）は `PluginNotPorted` を送出するに留める（GenTransparentMarshaler の
P5d と同じ判断）。
"""

from __future__ import annotations

import re
from typing import Any, ClassVar

from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import rb_print, sub_first, sym, to_s, utf8_literal


class DataPumpHolderPlugin(CelltypePlugin):
    _count: ClassVar[int] = (
        0  # @@count（何回、このプラグインが呼ばれたか。Ruby 版でも未使用）
    )

    def __init__(self, celltype: Any, option: Any) -> None:
        """celltype:: Celltype        セルタイプ（インスタンス）"""
        from tecsgen.core.syntaxobj.cdlstring import CDLString

        super().__init__(celltype, option)
        self._celltype = celltype
        self._plugin_arg_str = CDLString.remove_dquote(option)
        self._plugin_arg_list = {}
        self._cell_list: list[Any] = []

        ct_name = to_s(self._celltype.get_name())
        ct_gname = to_s(self._celltype.get_global_name())
        self._namespace_pre = to_s(self._celltype.get_namespace().get_global_name())
        self._signature_pre = sub_first(r"^t", "s", ct_name)
        self._signature_prefix = self._namespace_pre + "_" + self._signature_pre
        self._celltype_prefix = self._celltype.get_global_name()
        self._celltype_cdl_name = ct_gname + "_celltype.cdl"
        self._signature_cdl_name = ct_gname + "_signature.cdl"

        # @attr_list, @var_list および、その中身は参照するだけ
        self._attr_list = self._celltype.get_attribute_list()
        self._var_list = self._celltype.get_var_list()

        signame = sub_first(r"^t", "s", ct_name)
        self._get_signature = f"{signame}GetSignature"
        self._set_signature = f"{signame}SetSignature"
        self._datapump_celltype = f"{ct_name}DataPump"
        self._dataholder_celltype = f"{ct_name}DataHolder"
        self._datapumpholder_celltype = f"{ct_name}DataPumpHolder"
        self._set_signature_async = f"{signame}SetSignatureAsync"
        self._sync_adaptor_celltype = f"{ct_name}SyncAdaptor"
        self._async_adaptor_celltype = f"{ct_name}AsyncAdaptor"
        self.gen_get_set_signature()
        self.gen_pump_holder_celltype()

    def new_cell(self, cell: Any) -> None:
        """セルタイププラグインに対する新しいセルの報告。"""
        self._cell_list.append(cell)

    @classmethod
    def gen_post_code(cls, file: Any) -> None:
        """後ろの CDL コードを生成する（何も出力しない）。"""

    def gen_factory(self, file: Any) -> None:
        """tCelltype_factory.h に挿入するコードを生成する（何も出力しない）。"""

    def gen_cdl_file(self, file: Any) -> None:
        nsp = to_s(self._celltype.get_namespace_path())
        file.print(
            "/*\n"
            f"* This file is generated by DataPumpHolderPlugin from {nsp}\n"
            "*/\n"
            "\n"
            "// import DataPumpHolder.cdl which imports rpc.cdl and kernel.cdl\n"
            "import( <DataPumpHolder.cdl> );\n"
            "\n"
            f"// signature definition for data set & get in {nsp}\n"
        )
        file.print(f'import( "{self._signature_cdl_name}" );\n')
        file.print(f'import( "{self._celltype_cdl_name}" );\n')

    def _data_decls(self) -> list[Any]:
        return list(self._attr_list) + list(self._var_list)

    def _print_set_functions(self, file: Any) -> None:
        for decl in self._data_decls():
            size_is = decl.get_size_is()
            spec = f"[in, size_is({to_s(size_is)})]" if size_is is not None else "[in]"
            t = decl.get_type()
            file.print(
                "    [oneway]\n"
                f"      ER set_{to_s(decl.get_identifier())}( {spec}const {t.get_type_str()}\t"
                f"{to_s(decl.get_identifier())}{t.get_type_str_post()} );\n"
            )

    def gen_get_set_signature(self) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.plugin import CFile

        gen = get_context().gen
        rb_print(
            f"[DataPumpHolderPlugin] for DATA {to_s(self._celltype.get_name())}\n"
            f"      signatures in      {gen}/{self._signature_cdl_name}\n"
            f"                for  GET {self._get_signature}\n"
            f"                for  SET {self._set_signature}\n"
            f"      celltypes  in      {gen}/{self._celltype_cdl_name}\n"
            f"                for PUMP {self._datapump_celltype}\n"
            f"              for HOLDER {self._dataholder_celltype}\n"
            f"          for PUMPHOLDER {self._datapumpholder_celltype}\n"
        )
        nsp = to_s(self._celltype.get_namespace_path())
        file = CFile.open(
            f"{gen}/{to_s(self._celltype.get_global_name())}_signature.cdl", "w"
        )
        file.print(
            "/*\n"
            f"* This file is generated by DataPumpHolderPlugin from {nsp}\n"
            "*/\n"
            "\n"
            f"// Get signature for {nsp}\n"
            "//   Get signature is used for\n"
            "//      DataPump        cPubSide\n"
            "//      DataHolder      eSubSide\n"
            "//      DataPumpHolder  cPubSide, eSubSide\n"
            f"signature {self._get_signature}{{\n"
            "    // Sync Control functions\n"
            "    ER  waitForNewData(void);    // This function may block.\n"
            "    ER  dataReadDone(void);\n"
            "\n"
            "    // Data Access functions\n"
        )
        for decl in self._data_decls():
            ptr = "*" if decl.get_ptr_level() == 0 else ""
            size_is = decl.get_size_is()
            spec = (
                f"[out, size_is({to_s(size_is)})]" if size_is is not None else "[out]"
            )
            t = decl.get_type()
            file.print(
                f"    ER get_{to_s(decl.get_identifier())}( {spec}{t.get_type_str()}\t"
                f"{ptr}{to_s(decl.get_identifier())}{t.get_type_str_post()} );\n"
            )
        file.print("};\n")
        file.print(
            "\n"
            f"// Set signature for {nsp}\n"
            "//   Set signature is used for\n"
            "//      DataPump        cSubSide\n"
            "//      DataHolder      ePubSide\n"
            f"signature {self._set_signature}{{\n"
            "    // Sync Control functions\n"
            "    ER  waitForReadDone(void);    // This function may block.\n"
            "    [oneway]\n"
            "      ER  newDataReady(void);\n"
            "\n"
            "    // Data Set functions\n"
        )
        self._print_set_functions(file)
        file.print("};\n")
        file.print(
            "\n"
            f"// Set signature for {nsp}\n"
            "//   This Set signature is used for buffer asynchronous buffer communication.\n"
            "//   waitForReadDone is to notify new data arraival and\n"
            "//         executed asynchronously in client side and synchronously in server side.\n"
            f"signature {self._set_signature_async}{{\n"
            "    // Sync Control functions (async for RPC buffer)\n"
            "    [oneway]\n"
            "      ER  waitForReadDone(void);    // This function may block.\n"
            "    [oneway]\n"
            "      ER  newDataReady(void);\n"
            "\n"
            "    // Data Set functions\n"
        )
        self._print_set_functions(file)
        file.print("};\n")
        file.close()

    def _subst_heredoc(self, text: str) -> str:
        """ヒアドキュメント中の `#{@ivar}` を置換する。"""
        values = {
            "@celltype.get_namespace_path": to_s(self._celltype.get_namespace_path()),
            "@datapump_celltype": self._datapump_celltype,
            # Ruby 版のタイポ（@datholder_celltype は未定義で nil）なので空文字列になる
            "@datholder_celltype": "",
            "@datapumpholder_celltype": self._datapumpholder_celltype,
            "@dataholder_celltype": self._dataholder_celltype,
            "@get_signature": self._get_signature,
            "@set_signature": self._set_signature,
            "@set_signature_async": self._set_signature_async,
            "@sync_adaptor_celltype": self._sync_adaptor_celltype,
            "@async_adaptor_celltype": self._async_adaptor_celltype,
        }
        return re.sub(r"#\{([^}]*)\}", lambda m: values[m.group(1)], text)

    def gen_pump_holder_celltype(self) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.plugin import CFile

        file = CFile.open(
            f"{get_context().gen}/{to_s(self._celltype.get_global_name())}_celltype.cdl",
            "w",
        )
        file.print(self._subst_heredoc(_PUMP_HOLDER_HEAD))

        for decl in self._data_decls():
            size_is = decl.get_size_is()
            spec = (
                f"[size_is({to_s(size_is)})]\n        " if size_is is not None else ""
            )
            t = decl.get_type()
            file.print(
                f"     {spec}{t.get_type_str()}\t{to_s(decl.get_name())}{t.get_type_str_post()};\n"
            )
        file.print(self._subst_heredoc(_PUMP_HOLDER_TAIL))
        file.close()

    def gen_ep_func_body(
        self,
        file: Any,
        b_singleton: bool,
        ct_name: Any,
        global_ct_name: Any,
        sig_name: Any,
        ep_name: Any,
        func_name: Any,
        func_global_name: Any,
        func_type: Any,
        params: list[Any],
    ) -> None:
        """受け口関数の中身を生成する（P5 未移植。9.7.1 によりどのオラクルケースからも呼ばれない）。"""
        from tecsgen.core.plugin_module import PluginNotPorted

        raise PluginNotPorted("DataPumpHolderPlugin#gen_ep_func_body")

    def gen_preamble(
        self, file: Any, b_singleton: bool, ct_name: Any, global_ct_name: Any
    ) -> None:
        """受け口関数の preamble (C言語)を生成する。"""
        if ct_name == sym(self._sync_adaptor_celltype):
            file.print(
                utf8_literal(
                    "    /* このセルタイプは、waitForReadDone 関数を非 oneway 化するためのもの */\n"
                )
            )
        elif ct_name == sym(self._async_adaptor_celltype):
            file.print(
                utf8_literal(
                    "    /* このセルタイプは、waitForReadDone 関数を oneway 化するためのもの */\n"
                )
            )

    def find_decl(self, var_attr_name: Any) -> Any:
        """attr, var の中から探す（var_attr_name: Symbol。見つからなければ例外）。"""
        for decl in self._attr_list:
            if var_attr_name == decl.get_name():
                return decl
        for decl in self._var_list:
            if var_attr_name == decl.get_name():
                return decl
        raise RuntimeError(
            f"DataPumpHolderPlugin: Unknown data name {to_s(self._celltype.get_name())} "
            f"data:{to_s(var_attr_name)}"
        )


