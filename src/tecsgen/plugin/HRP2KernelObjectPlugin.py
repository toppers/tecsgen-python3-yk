"""HRP2KernelObjectPlugin.rb の移植（内部仕様9章）。HRP2 カーネルオブジェクト用セルタイププラグインの共通の親クラス。

Ruby 版は進行状況を `puts`／`print`／`p` で標準出力へ書く（正解データの標準出力に含まれる）ので、
同じ内容をそのまま書く。
"""

from __future__ import annotations

from typing import Any, ClassVar

from tecsgen.context import dbg_print, get_context
from tecsgen.core.cdl_types import ArrayType
from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import Y, inspect, rb_puts, to_s


class HRP2KernelObjectPlugin(CelltypePlugin):
    # カーネルオブジェクトセルタイプの管理
    # HRP2KernelObjectPluginクラスに対してメソッド呼出しを行うことを想定
    _checked: ClassVar[bool] = False
    _celltype_list: ClassVar[list[Any]] = []
    _region_list: ClassVar[list[Any]] = []

    @classmethod
    def reset(cls) -> None:
        HRP2KernelObjectPlugin._checked = False
        HRP2KernelObjectPlugin._celltype_list = []
        HRP2KernelObjectPlugin._region_list = []

    def __init__(self, celltype: Any, option: Any) -> None:
        super().__init__(celltype, option)
        # それぞれのカーネルオブジェクトを解析対象セルタイプに追加
        HRP2KernelObjectPlugin.set_celltype(celltype)

    def print_cfg_cre(self, file: Any, cell: Any, val: Any, tab: Any) -> None:
        """各種カーネルオブジェクトのCRE_*の出力。"""
        raise RuntimeError(
            f"called virtual method print_cfg_cre in {to_s(self._celltype.get_name())} plugin"
        )

    def print_cfg_sac(self, file: Any, val: Any, acv: Any) -> None:
        """各種カーネルオブジェクトのSAC_*の出力。"""
        raise RuntimeError(
            f"called virtual method print_cfg_sac in {to_s(self._celltype.get_name())} plugin"
        )

    def get_entry_ports_name_list(self) -> Any:
        """カーネルオブジェクトの各種アクセスの種別の受け口名を取得。"""
        raise RuntimeError(
            f"called virtual method get_entry_ports_name_list in {to_s(self._celltype.get_name())} plugin"
        )

    def string_cfg_cre(self, cell: Any, val: Any) -> Any:
        raise RuntimeError(
            f"called virtual method string_cfg_cre in {to_s(self._celltype.get_name())} plugin"
        )

    def gen_factory(self, file: Any) -> None:
        from tecsgen.core.generate import AppFile

        gen = get_context().gen
        ct = self._celltype
        rb_puts(f"===== begin {to_s(ct.get_name())} plugin =====")

        # 対象となるすべてのセルについて、受け口に結合されているセルの所属ドメインを解析
        if not HRP2KernelObjectPlugin.is_checked():
            HRP2KernelObjectPlugin.check_referenced_cells()
        else:
            rb_puts("***** already checked")

        # 追記するために AppFile を使う（文字コード変換されない）
        file2 = AppFile.open(f"{gen}/tecsgen.cfg")
        file2.print(f"\n/* Generated by {type(self).__name__} */\n\n")

        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            rb_puts(f"===== begin check my domain {to_s(cell.get_name())} =====")
            # attrの値をハッシュに入れる
            val: dict[Any, Any] = {}
            for a in ct.get_attribute_list():
                if isinstance(a.get_type(), ArrayType):
                    val[a.get_name()] = []
                    j = cell.get_join_list().get_item(a.get_name())
                    if j is not None:
                        # セル生成時に初期化する場合
                        for elem in j.get_rhs():
                            val[a.get_name()].append(to_s(elem))
                    elif a.get_initializer() is not None:
                        # セルタイプの初期化値を使う場合
                        for elem in a.get_initializer():
                            val[a.get_name()].append(to_s(elem))
                    else:
                        raise RuntimeError("attribute is not initialized")
                else:
                    j = cell.get_join_list().get_item(a.get_name())
                    if j is not None:
                        # セル生成時に初期化する場合
                        val[a.get_name()] = to_s(j.get_rhs())
                    elif a.get_initializer() is not None:
                        # セルタイプの初期化値を使う場合
                        val[a.get_name()] = to_s(a.get_initializer())
                    else:
                        raise RuntimeError("attribute is not initialized")
            # generate.rbを参考に $id$を置換
            if val.get(Y.id) is not None:
                rb_puts(val[Y.id])
                val[Y.id] = ct.subst_name(val[Y.id], ct.get_name_array(cell))
            cell_domain_root = cell.get_region().get_domain_root()
            cell_domain_type = cell_domain_root.get_domain_type()

            # CRE_XXX/DEF_XXXの生成
            if to_s(cell_domain_type.get_option()) != "OutOfDomain":
                # 保護ドメインに属する場合
                root_name = to_s(cell_domain_root.get_name())
                if not HRP2KernelObjectPlugin.include_region(root_name):
                    # その保護ドメインの.cfgが生成されていない場合
                    HRP2KernelObjectPlugin.set_region_list(root_name)
                    rb_puts(f"~~~~~ {root_name} is registered!")

                    if to_s(cell_domain_type.get_option()) == "trusted":
                        file2.print("KERNEL_DOMAIN{\n")
                    else:
                        file2.print(f"DOMAIN({root_name}){{\n")
                    file2.puts(f'\tINCLUDE("{gen}/tecsgen_{root_name}.cfg");')
                    file2.puts("}\n")
                else:
                    dbg_print(
                        f"~~~~~ {to_s(cell.get_region().get_name())} is included in"
                    )
                file3 = AppFile.open(f"{gen}/tecsgen_{root_name}.cfg")
                self.print_cfg_cre(file3, cell, val, "")
                file3.close()
            else:
                # 無所属の場合
                rb_puts(f"~~~~~ {to_s(cell_domain_root.get_name())} is OutOfDomain")
                self.print_cfg_cre(file2, cell, val, "")

            rb_puts(f"===== end check my domain {to_s(cell.get_name())} =====")
            # SAC_XXXの生成
            if val.get(Y.accessPattern) is not None:
                rb_puts(f"===== begin check regions {to_s(cell.get_name())} =====")
                acv: list[str] = []
                # アクセス許可ベクタの生成
                for acptnx in val[Y.accessPattern]:
                    # アクセス許可パターンの生成
                    if acptnx != "OMIT":
                        acv.append(acptnx)
                    elif to_s(cell_domain_type.get_option()) == "trusted":
                        acv.append("TACP_KERNEL")
                    elif to_s(cell_domain_type.get_option()) != "OutOfDomain":
                        acv.append(f"TACP({to_s(cell_domain_root.get_name())})")
                    else:
                        acv.append("TACP_SHARED")

                dbg_print("acv = ")
                rb_puts(inspect(acv))

                # 各種SACの生成
                domain_option = cell_domain_type.get_option()
                if domain_option != "OutOfDomain":
                    # 保護ドメインに属する場合
                    file3 = AppFile.open(
                        f"{gen}/tecsgen_{to_s(cell.get_region().get_name())}.cfg"
                    )
                    self.print_cfg_sac(file3, val, acv)
                    file3.close()
                else:
                    # 無所属の場合
                    self.print_cfg_sac(file2, val, acv)

                rb_puts(f"===== end check regions {to_s(cell.get_name())} =====")

        rb_puts(f"===== end {to_s(ct.get_name())} plugin =====")
        file2.close()

    @classmethod
    def is_checked(cls) -> bool:  # Ruby: isChecked
        return HRP2KernelObjectPlugin._checked

    @classmethod
    def check_referenced_cells(cls) -> None:
        dbg_print("===== begin check registered celltype =====\n")
        for ct in cls.get_celltype_list():
            dbg_print(to_s(ct.get_name()) + "\n")
        dbg_print("===== end check registered celltype =====\n")
        HRP2KernelObjectPlugin._checked = True

    @classmethod
    def set_celltype(cls, celltype: Any) -> None:
        HRP2KernelObjectPlugin._celltype_list.append(celltype)

    @classmethod
    def get_celltype_list(cls) -> list[Any]:
        return HRP2KernelObjectPlugin._celltype_list

    @classmethod
    def set_region_list(cls, region: Any) -> None:
        HRP2KernelObjectPlugin._region_list.append(region)

    @classmethod
    def include_region(cls, region: Any) -> bool:
        return region in HRP2KernelObjectPlugin._region_list

    @classmethod
    def include_celltype(cls, celltype: Any) -> bool:  # Ruby: include_celltype?
        return any(celltype is c for c in HRP2KernelObjectPlugin._celltype_list)
