"""FMPHandlerPlugin.rb の移植（内部仕様9章）。FMP のハンドラ（CFG_INT, CRE_ISR, DEF_INH など）を生成する。"""

from __future__ import annotations

import re
from typing import Any

from tecsgen.context import dbg_print, get_context
from tecsgen.core.syntaxobj.cdlstring import CDLString
from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import Y, sym, to_s

_HANDLER_LIST: dict[str, list[Any]] = {
    "INT_REQUEST": [
        Y.InClass,
        "CFG_INT( {{interruptNumber}}, { {{attribute}}, {{interruptPriority}} })",
    ],
    "INT_SERVICE_ROUTINE": [
        Y.InClass,
        "CRE_ISR( {{id}}, { {{attribute}}, $cbp$, {{interruptNumber}}, tISR_start, {{isrPriority}} })",
    ],
    "INT_HANDLER": [
        Y.InClass,
        "DEF_INH( {{interruptHandlerNumber}}, { {{attribute}}, $id$_start})",
    ],
    "CPU_EXCEPTION_HANDLER": [
        Y.InClass,
        "DEF_EXC( {{cpuExceptionHandlerNumber}}, { {{attribute}}, $id$_start})",
    ],
    # InClassの場合、初期化ルーチン、OutOfClassの場合、グローバル初期化ルーチン
    "INIT_ROUTINE": [
        Y.Any,
        "ATT_INI({ {{attribute}}, $cbp$, tInitializeRoutine_start })",
    ],
    # InClassの場合、終了ルーチン、OutOfClassの場合、グローバル終了ルーチン
    "TERM_ROUTINE": [
        Y.Any,
        "ATT_TER({ {{attribute}}, $cbp$, tTerminateRoutine_start })",
    ],
}

_RX_PLACEHOLDER = re.compile(r"\{\{([a-zA-Z0-9_]*?)\}\}")


class FMPHandlerPlugin(CelltypePlugin):
    def __init__(self, celltype: Any, option: Any) -> None:
        """celltype:: Celltype  セルタイプ（インスタンス）"""
        super().__init__(celltype, option)
        self._celltype = celltype
        self._class_name = CDLString.remove_dquote(option)
        self._cell_list: list[Any] = []

    def new_cell(self, cell: Any) -> None:
        """celltype プラグインを指定されたセルタイプのセルが生成された（新しいセルの報告）。"""
        self._cell_list.append(cell)
        if self._class_name not in _HANDLER_LIST:
            # this will be caused by wrong celltype definition in kernel.cdl.
            raise RuntimeError(f"FMPHandlerPlugin: {self._class_name} is unknown")
        root = cell.get_owner().get_class_root()
        if root is None:
            raise RuntimeError("root is nil")
        class_type = root.get_class_type()
        if class_type is None:
            self.cdl_error2(
                cell.get_locale(),
                "FMH9999 $1: is placed in root region. Handlers must be placed in CLS_PRC1, CLS_ALL_PRC1 specified region. Processos number can be varied.",
                cell.get_name(),
            )
            return
        dbg_print(
            f"FMPHandlerPlugin: new_cell {to_s(cell.get_name())} {to_s(class_type.get_option())} {to_s(_HANDLER_LIST[self._class_name][0])}\n"
        )
        if _HANDLER_LIST[self._class_name][0] == Y.InClass and class_type.get_option()[
            0
        ] == sym("global"):
            self.cdl_error2(
                cell.get_locale(),
                "FMH9999 $1: is placed global region. Kernel objects (not handlers) must be placed in CLS_PRC1, CLS_ALL_PRC1 specified region. Processos number can be varied.",
                cell.get_name(),
            )

    def print_cfg_cre(self, file: Any, cell: Any, indent: str) -> None:
        """CRE_XXXの出力。"""
        file.print(indent, f"/* FMPHandlerPlugin: {to_s(cell.get_name())} */\n")
        if self._class_name not in _HANDLER_LIST:
            raise RuntimeError(f"{self._class_name} is unknown")
        cfg_str = _HANDLER_LIST[self._class_name][1]
        file.print(indent)

        celltype = cell.get_celltype()
        name_array = celltype.get_name_array(cell)

        # {{attribute}} の置換
        def repl(m: re.Match[str]) -> str:
            return to_s(
                celltype.get_cell_attr_var_init_str(cell, name_array, sym(m.group(1)))
            )

        cfg_str2 = _RX_PLACEHOLDER.sub(repl, cfg_str)

        # $xxx$ の置換
        cfg_str3 = celltype.subst_name(cfg_str2, name_array)

        file.print(cfg_str3, ";\n")

    def gen_factory(self, file: Any) -> None:
        """tCelltype_factory.h に挿入するコードを生成する。"""
        from tecsgen.core.generate import AppFile
        from tecsgen.plugin.FMPPlugin import FMPPlugin

        f = AppFile.open(f"{get_context().gen}/tecsgen.cfg")
        f.print("/* Generated by FMPHandlerPlugin */\n")
        option_prev: Any = None
        indent = ""
        for cell in self._cell_list:
            root = cell.get_owner().get_class_root()

            class_type = root.get_class_type()
            if class_type.get_plugin().get_PU_attr()[Y.locality] == "only":
                # 処理単位用のクラス指定を使用
                option = class_type.get_plugin().get_PU_attr()[Y.class_name]
                comment = ""
            else:
                prc_id = class_type.get_plugin().get_PU_attr()[Y.processorID]
                option = FMPPlugin.get_prc_only(prc_id)
                dbg_print(f"FMPHandlerPlugin: get_only prc_id={to_s(prc_id)}\n")
                comment = (
                    f"       // class is changed from '{to_s(class_type.get_plugin().get_PU_attr()[Y.class_name])}' "
                    f"to processor restricted class '{to_s(option)}'"
                )
            if option != option_prev:
                if option_prev is not None and option_prev != Y.root:
                    f.print("}\n")
                if option != Y.root:
                    f.print(f"CLASS({to_s(option)}){{{comment}\n")
                    indent = "  "
                else:
                    indent = ""
                option_prev = option
            self.print_cfg_cre(f, cell, indent)
        if option_prev is not None and option_prev != Y.root:
            # 実際のところ nil になることはないハズ
            f.print("}\n")
        f.close()
