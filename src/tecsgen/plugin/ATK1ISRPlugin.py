"""ATK1ISRPlugin.rb の移植。TOPPERS/ATK1（OSEK）の割込みサービスルーチン定義（`ISR_tecsgen.oil`）と入口関数を生成する。"""

from __future__ import annotations

import re
from typing import Any

from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import gsub, sym, to_s, utf8_literal

_RX_QUOTED = re.compile(r'^"(.*)"$', re.MULTILINE)


def _unquote(obj: Any) -> str:
    return gsub(_RX_QUOTED, r"\1", to_s(obj))


class ATK1ISRPlugin(CelltypePlugin):
    def gen_factory(self, file: Any) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.generate import AppFile
        from tecsgen.core.plugin import CFile

        ctx = get_context()
        ct = self._celltype

        f2 = CFile.open(f"{ctx.gen}/ISR_tecsgen.oil", "w")
        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            jl = cell.get_join_list()
            f2.print(f"\tISR {to_s(cell.get_name())} {{\n")

            # CATEGORY / PRIORITY / ENTRY（entry は tecsgen の予約語のため Number を付加）
            for join_name, attr in (
                ("category", "CATEGORY"),
                ("priority", "PRIORITY"),
                ("entryNumber", "ENTRY"),
            ):
                join = jl.get_item(sym(join_name))
                if join is not None:
                    f2.print(f"\t\t{attr} = {to_s(join.get_rhs())};\n")

            # RESOURCE / MESSAGE
            for join_name, attr in (("resource", "RESOURCE"), ("message", "MESSAGE")):
                join2 = jl.get_item(sym(join_name))
                if join2 is not None:
                    for item in join2.get_rhs():
                        f2.print(f"\t\t{attr} = {_unquote(item)};\n")

            f2.print("\t};\n")
            f2.print("\n")
        f2.close()

        # 追記するために AppFile を使う（文字コード変換されない）
        f3 = AppFile.open(f"{ctx.gen}/tISR_tecsgen.{ctx.c_suffix}")
        f3.print("\n/* Generated by ATK1ISRPlugin */\n")
        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            cbp = to_s(ct.get_name_array(cell)[8])
            join2 = cell.get_join_list().get_item(sym("category"))
            if join2 is not None:
                if to_s(join2.get_rhs()) == "1":
                    f3.print("#if defined( OMIT_ISR1_ENTRY )\n")
                    f3.print(
                        utf8_literal(
                            "/* ISR1入り口未生成時は本関数を割込み関数指定する  */\n"
                        )
                    )
                    f3.print(
                        f"#pragma INTERRUPT  {to_s(cell.get_name())}\n"
                        "#endif  /* OMIT_ISR1_ENTRY  */\n"
                        "void  RxHwSerialInt( void );\n"
                        "void\n"
                        "RxHwSerialInt( void )\n"
                    )
                else:
                    f3.print(f"ISR({to_s(cell.get_name())})\n")
            f3.print(f"{{\n    CELLCB *p_cellcb = {cbp};\n    cBody_main();\n}}\n\n")
        f3.close()
