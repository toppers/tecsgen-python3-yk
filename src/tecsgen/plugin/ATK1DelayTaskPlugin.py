"""ATK1DelayTaskPlugin.rb の移植。遅延タスク（tDelayTaskBody）が待つイベントの `DeclareEvent` を生成する。"""

from __future__ import annotations

import re
from typing import Any

from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import sym, to_s

_RX_ADDRESS = re.compile(r"&(.*)")


class ATK1DelayTaskPlugin(CelltypePlugin):
    def gen_factory(self, file: Any) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.generate import AppFile

        ctx = get_context()

        # 追記するために AppFile を使う（文字コード変換されない）
        file2 = AppFile.open(f"{ctx.gen}/tDelayTaskBody_factory.{ctx.h_suffix}")
        file2.print("\n/* Generated by ATK1DelayTaskPlugin */\n\n")
        for cell in self._celltype.get_cell_list():
            if not cell.is_generate():
                continue
            join = cell.get_join_list().get_item(sym("event"))
            if join is not None:
                s = to_s(join.get_rhs())
                m = _RX_ADDRESS.search(s)
                if m is not None:
                    s = m.group(1)
                file2.print(f"DeclareEvent( {s} );\n")
        file2.close()
