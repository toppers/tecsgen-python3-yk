"""TECS2CBridgePlugin.rb の移植（内部仕様9章）。TECS から C の関数を呼び出すブリッジ（TECS => C 呼び出しプラグイン）。

@signature:: Signature   プラグインの対象となるシグニチャ
@option:: str   '"', '"' で囲まれた文字列
"""

from __future__ import annotations

from typing import Any, ClassVar

from tecsgen.plugin.SignaturePlugin import SignaturePlugin
from tecsgen.ruby_compat import sym, to_s, utf8_literal


class TECS2CBridgePlugin(SignaturePlugin):
    # シグニチャのグローバル名 → プラグインインスタンスのリスト（@@signature_list）
    _signature_list: ClassVar[dict[Any, list[Any]]] = {}

    @classmethod
    def reset(cls) -> None:
        """`@@signature_list` を初期化する（1プロセスで何度も実行するテスト用）。"""
        TECS2CBridgePlugin._signature_list = {}

    def __init__(self, signature: Any, option: Any) -> None:
        """signature:: Signature        シグニチャ（インスタンス）"""
        from tecsgen.context import get_context

        super().__init__(signature, option)

        self._signature = signature
        ctx = get_context()
        self._header_name = (
            f"{ctx.gen}/{to_s(self._signature.get_global_name())}.{ctx.h_suffix}"
        )
        self._celltype_name = sym(f"t{to_s(self._signature.get_global_name())}")

        self.parse_plugin_arg()

    def gen_cdl_file(self, file: Any) -> None:
        lst = TECS2CBridgePlugin._signature_list
        gname = self._signature.get_global_name()
        if lst.get(gname) is not None:
            lst[gname].append(self)
            self.cdl_warning(
                "T2CW001 signature '$1' duplicate. ignored current one",
                self._signature.get_namespace_path(),
            )
            return
        lst[gname] = [self]

        self.print_msg(
            f"  TECS2CBridgePlugin: [celltype] TECS2C::{to_s(self._celltype_name)}. "
            "Create cell then join to entry port 'eEntry' from the caller cell\n"
        )
        file.print(
            "namespace nTECS2C{\n"
            "  [singleton]\n"
            f"  celltype {to_s(self._celltype_name)} {{\n"
            "    [inline]\n"
            f"    entry {to_s(self._signature.get_namespace_path())} eEnt;\n"
            "  };\n"
            "};\n"
        )

    @classmethod
    def gen_post_code(cls, file: Any) -> None:
        """後ろのコードを生成する（何も出力しない）。"""

    def gen_ep_func_body(
        self,
        file: Any,
        b_singleton: bool,
        ct_name: Any,
        global_ct_name: Any,
        sig_name: Any,
        ep_name: Any,
        func_name: Any,
        func_global_name: Any,
        func_type: Any,
        params: list[Any],
    ) -> None:
        """受け口関数の本体(C言語)を生成する。"""
        ret_type = func_type.get_type()
        b_ret_void = ret_type.is_void()

        if not b_ret_void:
            file.print(f"  {ret_type.get_type_str()}  retval;\n")

        if not b_singleton:
            file.print(
                f"  {to_s(ct_name)}_CB    *p_cellcb;\n"
                "  if( VALID_IDX( idx ) ){\n"
                f"    p_cellcb = {to_s(global_ct_name)}_GET_CELLCB(idx);\n"
                "  }else{\n"
                + utf8_literal("     /* エラー処理コードをここに記述 */\n")
                + "  }\n\n"
            )

        if not b_ret_void:
            file.print("  retval = ")
        else:
            file.print("  ")

        file.print(f"{to_s(func_name)}(")

        delim = ""
        for param in params:
            file.printf(f"{delim} {to_s(param.get_name())}")
            delim = ","

        file.print(" );\n")

        if not b_ret_void:
            file.print("  return retval;\n")

    def gen_postamble(
        self, file: Any, b_singleton: bool, ct_name: Any, global_ct_name: Any
    ) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.plugin import CFile

        # generate header file here, NOT postamble
        file2 = CFile.open(self._header_name, "w")
        file2.print(
            "/*\n"
            " * This file was generated by TECS2CBridgePlugin and has prototype\n"
            f" * decalarations of functions in signature '{to_s(self._signature.get_namespace_path())}'\n"
            " */\n"
            "\n"
            f'#include "global_tecsgen.{get_context().h_suffix}"\n'
            "\n"
        )
        for f in self._signature.get_function_head_array():
            decl = f.get_declarator()
            func_type = decl.get_type()
            params = func_type.get_paramlist().get_items()
            func_name = decl.get_name()

            ret_type = func_type.get_type()

            file2.print(f"{ret_type.get_type_str()}  {to_s(func_name)}(")

            delim = ""
            for param in params:
                file2.printf(f"{delim} {to_s(param.get_name())}")
                delim = ","

            file2.print(f" ){ret_type.get_type_str_post()};\n")

        file2.close()
