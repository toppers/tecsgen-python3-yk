"""TransparentRPCSignaturePlugin.rb の移植（内部仕様9章）。Transparent RPC のチャンネルを生成するシグニチャプラグイン。

tecsgen-rb で追加された（r3304 には無い。r3304 では RPCPlugin・DataPumpHolderPlugin が生成する
`generate(TransparentRPCSignaturePlugin, ...)` が `P2001 ... fail to load plugin` で失敗していた）。

mikan through plugin: namespace が考慮されていない（Ruby 版の記述。直さずそのまま移植する）

シグニチャごとに、マーシャラ・アンマーシャラのセルタイプ（GenTransparentMarshaler）と、
クライアント側・サーバ側・結合したチャンネルの composite セルタイプを CDL として書き出す。
"""

from __future__ import annotations

from typing import Any, ClassVar

from tecsgen.context import get_context
from tecsgen.core.plugin import CFile
from tecsgen.plugin.lib.GenParamCopy import GenParamCopy
from tecsgen.plugin.lib.GenTransparentMarshaler import GenTransparentMarshaler
from tecsgen.plugin.SignaturePlugin import SignaturePlugin
from tecsgen.ruby_compat import Symbol, rb_print, sym, to_s, truthy

# チャンネルのセルタイプを書き出す CDL（Ruby の heredoc。#{...} を %(...)s に置き換えてある）。
# 末尾の空行・「/ */」の綴りも Ruby 版のまま
_CHANNEL_CDL = """\
/*
 * generated by TransparentRPCSignaturePlugin
 * for signature %(sig_path)s
/ */
import( "%(marshaler_file)s" );
import( <rpc/tDataqueueOWChannel.cdl> );

/****** Client Side Channel / ******/
composite %(rpc_name)s_ClientSide {
  /* Interface / */
  entry %(sig_path)s eThroughEntry;
  call sTDR       cTDR;
  call sEventflag cEventflag;

  /* Implementation / */
%(semaphore1)s
  cell %(marshaler_name)s %(sig_gname)s_marshaler{
    cTDR         => composite.cTDR;
    cEventflag   => composite.cEventflag;
%(semaphore2)s  };
  composite.eThroughEntry => %(sig_gname)s_marshaler.eClientEntry;
};

/****** Server Side Channel / ******/
composite %(rpc_name)s_ServerSide {
  /* Interface / */
  call %(sig_path)s cServerCall;
  call sTDR       cTDR;
  call sEventflag cEventflag;
  entry sTaskBody eMain;

  /* Implementation / */
%(alloc_cell)s  cell %(unmarshaler_name)s %(sig_gname)s_unmarshaler{
    cTDR        => composite.cTDR;
    cEventflag  => composite.cEventflag;
    cServerCall => composite.cServerCall;
%(alloc_call_port_join)s  };
  cell tRPCDedicatedTaskMain RPCTaskMain{
    cMain = %(sig_gname)s_unmarshaler.eUnmarshalAndCallFunction;
  };
  composite.eMain => RPCTaskMain.eMain;
};

/****** Client & Server Combined Channel / ******/
[active]
composite %(rpc_name)s {
  /* Interface / */
  attr {
    PRI taskPriority;
    size_t  stackSize = 4096;
    ATR     attribute = C_EXP( "TA_ACT" );  /* marshaler starts at the beginning / */
  };
  entry %(sig_path)s eThroughEntry;
  call %(sig_path)s %(call_port)s;
  call sTDR       cTDR;
  call sEventflag cEventflag;

  /* Implementation / */
  cell %(rpc_name)s_ClientSide RPCChannel_ClientSide{
    cTDR        => composite.cTDR;
    cEventflag  => composite.cEventflag;
  };
  cell %(rpc_name)s_ServerSide RPCChannel_ServerSide{
    cTDR        => composite.cTDR;
    cEventflag  => composite.cEventflag;
    cServerCall => composite.%(call_port)s;
  };
  cell tTask Task {
    cTaskBody = RPCChannel_ServerSide.eMain;
    priority  = composite.taskPriority;
    attribute = composite.attribute;
    stackSize = composite.stackSize;
  };
  composite.eThroughEntry => RPCChannel_ClientSide.eThroughEntry;
};

/****** Client & Server Combined Channel / ******/
[active]
composite %(rpc_name_full)s {
  /* Interface / */
  attr {
    PRI taskPriority;
    size_t  stackSize = 4096;
    ATR     attribute = C_EXP( "TA_ACT" );  /* marshaler starts at the beginning / */
  };
  entry %(sig_path)s eThroughEntry;
  call %(sig_path)s %(call_port)s;

  /* Implementation / */
  cell %(rpc_name)s_ClientSide RPCChannel_ClientSide{
    cTDR         = Channel.eTDR;
    cEventflag   = Channel.eEventflag;
  };
  cell %(rpc_name)s_ServerSide RPCChannel_ServerSide{
    cTDR         = Channel.eTDR;
    cEventflag   = Channel.eEventflag;
    cServerCall => composite.%(call_port)s;
  };
  cell tDataqueueOWChannel Channel {
  };
  cell tTask Task {
    cTaskBody = RPCChannel_ServerSide.eMain;
    priority  = composite.taskPriority;
    attribute = composite.attribute;
    stackSize = composite.stackSize;
  };
  composite.eThroughEntry => RPCChannel_ClientSide.eThroughEntry;
};

"""


class TransparentRPCSignaturePlugin(
    GenParamCopy, GenTransparentMarshaler, SignaturePlugin
):
    # セルタイプの重複排除用。ThroughPlugin（RPCPlugin など）とは別の Hash
    # （SignaturePlugin の子で、ThroughPlugin の子ではないので共有されない）
    _generated_celltype: ClassVar[dict[Any, list[Any]]] = {}

    # このプラグイン専用のオプション（GenTransparentMarshaler.RPC_PLUGIN_ARG_PROC の複製 + 追加）
    TRANSPARENT_RPC_PLUGIN_ARG_PROC: ClassVar[dict[str, Any]] = {}

    @classmethod
    def reset(cls) -> None:
        TransparentRPCSignaturePlugin._generated_celltype = {}

    def __init__(self, signature: Any, option: Any) -> None:
        """説明は ThroughPlugin (plugin.rb) を参照。"""
        super().__init__(signature, option)
        self._b_no_client_semaphore = False
        self._semaphore_celltype: Any = "tSemaphore"
        self._b_datapumpholder = False
        self._call_port_name = sym("cCall")

        # オプション：GenTransparentMarshaler 参照
        self._plugin_arg_check_proc_tab = (
            TransparentRPCSignaturePlugin.TRANSPARENT_RPC_PLUGIN_ARG_PROC
        )
        self.parse_plugin_arg()

        # ThroughPlugin では、cCall (固定)。SignaturePlugin は、デフォルトではシグニチャ名由来の
        # 呼び口名が付くので、これを ThroughPlugin に合わせて cCall に変更する。
        # Ruby 版は "#{signature}Cell"（Signature オブジェクトの to_s。出力には使われない dummy）
        cell_name = f"{to_s(signature.get_name())}Cell"
        self.initialize_transparent_marshaler(cell_name)

        channel_head_append = "DPH" if self._b_datapumpholder is True else ""

        self._rpc_channel_celltype_name = (
            f"tRPCPlugin{channel_head_append}_{to_s(self._tdr_celltype)}_"
            f"{to_s(self._signature.get_global_name())}"
        )
        self._rpc_channel_celltype_name_full = (
            f"tRPCPlugin{channel_head_append}_{to_s(self._tdr_celltype)}_"
            f"{to_s(self._channel_celltype)}_{to_s(self._signature.get_global_name())}"
        )
        self._rpc_channel_celltype_file_name = (
            f"{get_context().gen}/{self._rpc_channel_celltype_name}.cdl"
        )

        if self._signature.need_PPAllocator() and self._pp_allocator_size is None:
            self.cdl_error(
                "RPC9999 PPAllocatorSize must be speicified for oneway [in] array"
            )

    def gen_cdl_file(self, file: Any) -> None:
        """CDL ファイルの生成。"""
        self.gen_plugin_decl_code(file)

    def gen_plugin_decl_code(self, file: Any) -> None:
        """plugin の宣言コード (celltype の定義) 生成。"""
        file.print(
            "/*\n"
            " * genratedy by TransparentMarhsalerPlugin\n"
            "/ */\n"
            f'import( "{self._rpc_channel_celltype_file_name}" );\n'
        )

        ct_name = self._rpc_channel_celltype_file_name
        # このセルタイプ（同じシグニチャ）は既に生成されているか？
        generated = TransparentRPCSignaturePlugin._generated_celltype
        if generated.get(ct_name) is None:
            generated[ct_name] = [self]
        else:
            generated[ct_name].append(self)
            return

        self.gen_marshaler_celltype()
        rb_print(
            "[TransparentRPCSignaturePlugin]\n"
            f"           create celltype {self._rpc_channel_celltype_name}\n"
            f"                        in {self._rpc_channel_celltype_file_name}\n"
        )

        if truthy(self._pp_allocator_size):
            alloc_cell = (
                "  cell tPPAllocator PPAllocator {\n"
                f"    heapSize = {to_s(self._pp_allocator_size)};\n"
                "  };\n"
            )
            alloc_call_port_join = "    cPPAllocator = PPAllocator.ePPAllocator;\n"
        else:
            alloc_cell = ""
            alloc_call_port_join = ""

        if self._b_no_client_semaphore is False:
            semaphore1 = (
                '  /* Semaphore for Multi-task use ("specify noClientSemaphore" option to delete this) / */\n'
                f"  cell {to_s(self._semaphore_celltype)} Semaphore {{\n"
                "    initialCount = 1;\n"
                '    attribute = C_EXP( "TA_NULL" );\n'
                "  };\n"
            )
            semaphore2 = "    cLockChannel = Semaphore.eSemaphore;\n"
        else:
            semaphore1 = ""
            semaphore2 = ""

        f = CFile.open(self._rpc_channel_celltype_file_name, "w")
        # 同じ内容を二度書く可能性あり (AppFile は不可)
        f.print(
            _CHANNEL_CDL
            % {
                "sig_path": to_s(self._signature.get_namespace_path()),
                "marshaler_file": self._marshaler_celltype_file_name,
                "rpc_name": self._rpc_channel_celltype_name,
                "rpc_name_full": self._rpc_channel_celltype_name_full,
                "semaphore1": semaphore1,
                "semaphore2": semaphore2,
                "marshaler_name": self._marshaler_celltype_name,
                "unmarshaler_name": self._unmarshaler_celltype_name,
                "sig_gname": to_s(self._signature.get_global_name()),
                "alloc_cell": alloc_cell,
                "alloc_call_port_join": alloc_call_port_join,
                "call_port": to_s(self._call_port_name),
            }
        )
        # mikan stackSize option & 最新 tecs_package 対応
        f.close()

    def set_noClientSemaphore(self, rhs: Any) -> None:
        """プラグイン引数 noClientSemaphore のチェック。"""
        rhs_sym = sym(rhs)
        if rhs_sym == Symbol("true"):
            self._b_no_client_semaphore = True
        elif rhs_sym == Symbol("false"):
            self._b_no_client_semaphore = False
        else:
            self.cdl_error("RPC9999 specify true or false for noClientSemaphore")

    def set_semaphoreCelltype(self, rhs: Any) -> None:
        """プラグイン引数 semaphoreCelltype のチェック。"""
        from tecsgen.core.componentobj.celltype import Celltype
        from tecsgen.core.componentobj.compositecelltype import CompositeCelltype
        from tecsgen.core.componentobj.namespace import Namespace
        from tecsgen.core.componentobj.namespacepath import NamespacePath

        self._semaphore_celltype = sym(rhs)
        nsp = NamespacePath.analyze(to_s(self._semaphore_celltype))
        obj = Namespace.find(nsp)
        if not isinstance(obj, (Celltype, CompositeCelltype)):
            self.cdl_error(
                "RPC9999 semaphoreCelltype '$1' not celltype or not defined", rhs
            )

    def set_datapumpholder(self, rhs: Any) -> None:
        """プラグイン引数 DataPumpHolder のチェック。"""
        rhs_sym = sym(rhs)
        if rhs_sym == Symbol("true"):
            self._b_datapumpholder = True
        elif rhs_sym == Symbol("false"):
            self._b_datapumpholder = False
        else:
            self.cdl_error("RPC9999 specify true or false for datapumpholder")


TransparentRPCSignaturePlugin.TRANSPARENT_RPC_PLUGIN_ARG_PROC = {
    **GenTransparentMarshaler.RPC_PLUGIN_ARG_PROC,
    "noClientSemaphore": lambda obj, rhs: obj.set_noClientSemaphore(rhs),
    "semaphoreCelltype": lambda obj, rhs: obj.set_semaphoreCelltype(rhs),
    "DataPumpHolder": lambda obj, rhs: obj.set_datapumpholder(rhs),
}
