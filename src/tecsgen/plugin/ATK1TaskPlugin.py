"""ATK1TaskPlugin.rb の移植。TOPPERS/ATK1（OSEK）のタスク定義（`TASK_tecsgen.oil`）とタスク本体を生成する。"""

from __future__ import annotations

import re
from typing import Any

from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import gsub, sym, to_s

_RX_QUOTED = re.compile(r'^"(.*)"$', re.MULTILINE)


def _unquote(obj: Any) -> str:
    return gsub(_RX_QUOTED, r"\1", to_s(obj))


class ATK1TaskPlugin(CelltypePlugin):
    def gen_factory(self, file: Any) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.generate import AppFile
        from tecsgen.core.plugin import CFile

        ctx = get_context()
        ct = self._celltype

        f2 = CFile.open(f"{ctx.gen}/TASK_tecsgen.oil", "w")

        # Ruby 版は `++extended_task_count;` で増やしているつもりだが、Ruby の `++x` は
        # `+(+x)` で何もしないため、常に 1 のまま（そのまま再現する）
        extended_task_count = 1

        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            jl = cell.get_join_list()
            f2.print(f"\tTASK {to_s(cell.get_name())} {{\n")

            # AUTOSTART
            join = jl.get_item(sym("autoStart"))
            if join is not None:
                s = to_s(join.get_rhs())
                if s == "TRUE":
                    join2 = jl.get_item(sym("appMode"))
                    if join2 is not None:
                        f2.print("\t\tAUTOSTART = TRUE {\n")
                        for mode in join2.get_rhs():
                            f2.print(f"\t\t\tAPPMODE = {_unquote(mode)};\n")
                        f2.print("\t\t};\n")
                    else:
                        f2.print("\t\tAUTOSTART = TRUE;\n")
                elif s == "FALSE":
                    f2.print("\t\tAUTOSTART = FALSE;\n")

            # PRIORITY
            join = jl.get_item(sym("priority"))
            if join is not None:
                f2.print(f"\t\tPRIORITY = {to_s(join.get_rhs())};\n")

            # ACTIVATION
            join = jl.get_item(sym("activation"))
            if join is not None:
                f2.print(f"\t\tACTIVATION = {to_s(join.get_rhs())};\n")

            # SCHEDULE
            join = jl.get_item(sym("schedule"))
            if join is not None:
                f2.print(f"\t\tSCHEDULE = {_unquote(join.get_rhs())};\n")

            # EVENT
            join = jl.get_item(sym("event"))
            if join is not None:
                for evt in join.get_rhs():
                    s = _unquote(evt)
                    if s != "OMISSIBLE":
                        f2.print(f"\t\tEVENT = {s};\n")
                for evt in join.get_rhs():
                    if _unquote(evt) != "OMISSIBLE":
                        cell.set_specified_id(extended_task_count)
                        break

            # RESOURCE
            join = jl.get_item(sym("resource"))
            if join is not None:
                for res in join.get_rhs():
                    s = _unquote(res)
                    if s != "OMISSIBLE":
                        f2.print(f"\t\tRESOURCE = {s};\n")

            # MESSAGE
            join = jl.get_item(sym("message"))
            if join is not None:
                for msg in join.get_rhs():
                    s = _unquote(msg)
                    if s != "OMISSIBLE":
                        f2.print(f"\t\tMESSAGE = {s};\n")

            # STACKSIZE
            join = jl.get_item(sym("stackSize"))
            if join is not None:
                f2.print(f"\t\tSTACKSIZE = {to_s(join.get_rhs())};\n")

            f2.print("\t};\n")
            f2.print("\n")
        f2.close()

        # 追記するために AppFile を使う（文字コード変換されない）
        f3 = AppFile.open(f"{ctx.gen}/tTask_tecsgen.{ctx.c_suffix}")
        f3.print("\n/* Generated by ATK1TaskPlugin */\n")
        for cell in ct.get_cell_list():
            if cell.is_generate():
                cbp = to_s(ct.get_name_array(cell)[8])
                f3.print(
                    f"TASK({to_s(cell.get_name())})\n"
                    "{\n"
                    f"    CELLCB *p_cellcb = {cbp};\n"
                    "    cBody_main();\n"
                    "    terminate();\n"
                    "}\n"
                    "\n"
                )
        f3.close()
