"""ATK1AlarmPlugin.rb の移植。TOPPERS/ATK1（OSEK）のアラーム定義（`ALARM_tecsgen.oil`）とコールバックを生成する。"""

from __future__ import annotations

import re
from typing import Any

from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import gsub, sym, to_s

_RX_QUOTED = re.compile(r'^"(.*)"$', re.MULTILINE)


def _unquote(obj: Any) -> str:
    return gsub(_RX_QUOTED, r"\1", to_s(obj))


class ATK1AlarmPlugin(CelltypePlugin):
    def gen_factory(self, file: Any) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.generate import AppFile
        from tecsgen.core.plugin import CFile

        ctx = get_context()
        ct = self._celltype

        f2 = CFile.open(f"{ctx.gen}/ALARM_tecsgen.oil", "w")
        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            jl = cell.get_join_list()
            f2.print(f"\tALARM {to_s(cell.get_name())} {{\n")

            # Ruby 版の `str` はブロック内のローカル変数で、セルごとに nil から始まり、
            # 結合が無い項目では直前の項目で代入された値を引き継ぐ（そのまま再現する）
            s: str | None = None

            # COUNTER
            join = jl.get_item(sym("counter"))
            if join is not None:
                s = _unquote(join.get_rhs())
                f2.print(f"\t\tCOUNTER = {s};\n")

            # ACTION
            join = jl.get_item(sym("action"))
            if join is not None:
                s = _unquote(join.get_rhs())

            if s == "SETEVENT":
                f2.print(f"\t\tACTION = {s} {{\n")
                join2 = jl.get_item(sym("task"))
                if join2 is not None:
                    s = _unquote(join2.get_rhs())
                    f2.print(f"\t\t\tTASK = {s};\n")
                join2 = jl.get_item(sym("event"))
                if join2 is not None:
                    s = _unquote(join2.get_rhs())
                    f2.print(f"\t\t\tEVENT = {s};\n")
                f2.print("\t\t};\n")
            elif s == "ACTIVATETASK":
                f2.print(f"\t\tACTION = {s} {{\n")
                join2 = jl.get_item(sym("task"))
                if join2 is not None:
                    s = _unquote(join2.get_rhs())
                    f2.print(f"\t\t\tTASK = {s};\n")
                f2.print("\t\t};\n")
            elif s == "ALARMCALLBACK":
                f2.print(f"\t\tACTION = {s} {{\n")
                join2 = jl.get_item(sym("callbackName"))
                if join2 is not None:
                    s = to_s(join2.get_rhs())
                    f2.print(f"\t\t\tALARMCALLBACKNAME = {s};\n")
                f2.print("\t\t};\n")

            # AUTOSTART
            join = jl.get_item(sym("autoStart"))
            if join is not None:
                s = to_s(join.get_rhs())

            if s == "TRUE":
                f2.print("\t\tAUTOSTART = TRUE {\n")
                join2 = jl.get_item(sym("alarmTime"))
                if join2 is not None:
                    f2.print(f"\t\t\tALARMTIME = {to_s(join2.get_rhs())};\n")
                join2 = jl.get_item(sym("cycleTime"))
                if join2 is not None:
                    f2.print(f"\t\t\tCYCLETIME = {to_s(join2.get_rhs())};\n")
                join2 = jl.get_item(sym("appMode"))
                if join2 is not None:
                    for mode in join2.get_rhs():
                        f2.print(f"\t\t\tAPPMODE = {_unquote(mode)};\n")
                f2.print("\t\t};\n")
            else:
                f2.print("\t\tAUTOSTART = FALSE;\n")

            f2.print("\t};\n")
            f2.print("\n")
        f2.close()

        # 追記するために AppFile を使う（文字コード変換されない）
        f3 = AppFile.open(f"{ctx.gen}/tAlarm_tecsgen.{ctx.c_suffix}")
        f3.print("\n/* Generated by ATK1AlarmPlugin */\n")
        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            join2 = cell.get_join_list().get_item(sym("callbackName"))
            if join2 is not None:
                name = _unquote(join2.get_rhs())
                cbp = to_s(ct.get_name_array(cell)[8])
                f3.print(
                    f"ALARMCALLBACK( {name} );\n"
                    f"ALARMCALLBACK( {name} )\n"
                    "{\n"
                    f"    CELLCB *p_cellcb = {cbp};\n"
                    "    cBody_main();\n"
                    "}\n"
                    "\n"
                )
        f3.close()
