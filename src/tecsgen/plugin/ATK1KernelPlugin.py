"""ATK1KernelPlugin.rb の移植。TOPPERS/ATK1（OSEK）の OS 定義（`Kernel_tecsgen.oil`）とフック関数を生成する。"""

from __future__ import annotations

import re
from typing import Any, ClassVar

from tecsgen.plugin.CelltypePlugin import CelltypePlugin
from tecsgen.ruby_compat import gsub, sym, to_s

_RX_QUOTED = re.compile(r'^"(.*)"$', re.MULTILINE)

# (結合名, OIL の属性名)
_OS_ATTRS = (
    ("useStartupHook", "STARTUPHOOK"),
    ("useErrorHook", "ERRORHOOK"),
    ("useShutdownHook", "SHUTDOWNHOOK"),
    ("usePreTaskHook", "PRETASKHOOK"),
    ("usePostTaskHook", "POSTTASKHOOK"),
    ("useGetServiceId", "USEGETSERVICEID"),
    ("useParameterAccess", "USEPARAMETERACCESS"),
    ("useResourceScheduler", "USERESSCHEDULER"),
)


class ATK1KernelPlugin(CelltypePlugin):
    _cell_list: ClassVar[list[Any]] = []

    @classmethod
    def reset(cls) -> None:
        """`@@cell_list` を初期化する（1プロセスで何度も実行するテスト用）。"""
        ATK1KernelPlugin._cell_list = []

    def new_cell(self, cell: Any) -> None:
        ATK1KernelPlugin._cell_list.append(cell)

    def gen_factory(self, file: Any) -> None:
        from tecsgen.context import get_context
        from tecsgen.core.generate import AppFile
        from tecsgen.core.plugin import CFile

        ctx = get_context()
        ct = self._celltype

        f2 = CFile.open(f"{ctx.gen}/Kernel_tecsgen.oil", "w")
        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            jl = cell.get_join_list()
            f2.print(f"\tOS {to_s(cell.get_name())} {{\n")
            join = jl.get_item(sym("status"))
            if join is not None:
                f2.print(
                    f"\t\tSTATUS = {gsub(_RX_QUOTED, r'\1', to_s(join.get_rhs()))};\n"
                )
            for join_name, attr in _OS_ATTRS:
                join = jl.get_item(sym(join_name))
                if join is not None:
                    f2.print(f"\t\t{attr} = {to_s(join.get_rhs())};\n")
            f2.print("\t};\n\n")
        f2.close()

        # 追記するために AppFile を使う（文字コード変換されない）
        f3 = AppFile.open(f"{ctx.gen}/tKernel_tecsgen.{ctx.c_suffix}")
        f3.print("\n/* Generated by ATK1KernelPlugin */\n\n")
        for cell in ct.get_cell_list():
            if not cell.is_generate():
                continue
            jl = cell.get_join_list()
            cbp = to_s(ct.get_name_array(cell)[8])

            def use(join_name: str, jl: Any = jl) -> bool:
                join = jl.get_item(sym(join_name))
                return join is not None and to_s(join.get_rhs()) == "TRUE"

            if use("useStartupHook"):
                f3.print(
                    "#ifdef USE_STARTUPHOOK\n"
                    "void StartupHook(void)\n"
                    "{\n"
                    f"/*    CELLCB *p_cellcb = {cbp}; */\n"
                    "    INT32 i;\n"
                    "    for(i = 0; i < N_CP_cStartupHookBody; i++){\n"
                    "        cStartupHookBody_main(i);\n"
                    "    }\n"
                    "}\n"
                    "#endif /* USE_STARTUPHOOK */\n"
                )
            if use("useErrorHook"):
                f3.print(
                    "#ifdef USE_ERRORHOOK\n"
                    "void ErrorHook(StatusType ercd)\n"
                    "{\n"
                    f"/*    CELLCB *p_cellcb = {cbp}; */\n"
                    "    cErrorHookBody_main( ercd );\n"
                    "}\n"
                    "#endif /* USE_ERRORHOOK */\n"
                    "\n"
                )
            if use("useShutdownHook"):
                f3.print(
                    "#ifdef USE_SHUTDOWNHOOK\n"
                    "void ShutdownHook(StatusType ercd)\n"
                    "{\n"
                    f"/*    CELLCB *p_cellcb = {cbp}; */\n"
                    "    INT32 i;\n"
                    "    for(i = 0; i < N_CP_cShutdownHookBody; i++){\n"
                    "        cShutdownHookBody_main( i, ercd );\n"
                    "    }\n"
                    "}\n"
                    "#endif /* USE_SHUTDOWNHOOK */\n"
                    "\n"
                )
            if use("usePreTaskHook"):
                f3.print(
                    "#ifdef USE_PRETASKHOOK\n"
                    "void PreTaskHook(void)\n"
                    "{\n"
                    f"/*    CELLCB *p_cellcb = {cbp}; */\n"
                    "    cPreTaskHookBody_main();\n"
                    "}\n"
                    "#endif /* USE_PRETASKHOOK */\n"
                    "\n"
                )
            if use("usePostTaskHook"):
                f3.print(
                    "#ifdef USE_POSTTASKHOOK\n"
                    "void PostTaskHook(void)\n"
                    "{\n"
                    f"/*    CELLCB *p_cellcb = {cbp}; */\n"
                    "    cPostTaskHookBody_main();\n"
                    "}\n"
                    "#endif /* USE_POSTTASKHOOK */\n"
                    "\n"
                )
        f3.close()

    @classmethod
    def gen_post_code(cls, file: Any) -> None:
        for cell in ATK1KernelPlugin._cell_list:
            join = cell.get_join_list().get_item(sym("useResourceScheduler"))
            if join is not None and to_s(join.get_rhs()) == "TRUE":
                file.print(
                    'cell tResource RES_SCHEDULER {\n\tproperty = "STANDARD";\n};\n'
                )
