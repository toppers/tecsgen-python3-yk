# racc が生成したパーサ（bnf.tab.rb・C_parser.tab.rb）から、LALR 表を JSON に書き出す。
# 表の解釈は tools/port/gen_racc_tables.py が行う。
#
# 使い方: ruby dump_racc_tables.rb <*.tab.rb> <クラス名>  > out.json
# 作業コピーが CRLF でも結果が変わらないよう、読み込み時に CRLF を LF に直す。
require "json"
require "racc/parser"

path, class_name = ARGV.fetch(0), ARGV.fetch(1)
src = File.binread(path).force_encoding("UTF-8").gsub("\r\n", "\n")
eval(src, TOPLEVEL_BINDING, path)

klass = Object.const_get(class_name)
arg = klass::Racc_arg
names = %w[action_table action_check action_default action_pointer
           goto_table goto_check goto_default goto_pointer
           nt_base reduce_table token_table shift_n reduce_n use_result]
out = {}
names.each_with_index do |name, i|
  v = arg[i]
  case name
  when "reduce_table"
    out[name] = v.map { |x| x.is_a?(Symbol) ? x.to_s : x }
  when "token_table"
    # キーは Symbol（:IDENTIFIER）・String（"{"）・false（EOF）
    out[name] = v.map { |k, id| [k.is_a?(Symbol) ? "sym" : k.class.to_s.downcase, k.to_s, id] }
  else
    out[name] = v
  end
end
out["token_to_s_table"] = klass::Racc_token_to_s_table
out["debug_parser"] = klass::Racc_debug_parser
out["racc_version_comment"] = src[/generated by Racc [\d.]+/]
puts JSON.generate(out)
